//! The authoring ladder: what a world is allowed to be evidence for (27.01–27.04).
//!
//! §27 authors worlds three ways, in three consecutive modules, and it is easy to read them as a
//! quality ranking with observed data at the top. They are not a ranking. They are **three
//! different epistemic objects**, and each answers a question the other two cannot:
//!
//! | Rung | Module | What it is good for | What it cannot say |
//! | --- | --- | --- | --- |
//! | [`Rung::Observed`] | 27.02 | reproducibility, analysis, evidence selection | any counterfactual the study design did not identify |
//! | [`Rung::SemiSynthetic`] | 27.03 | robustness and failure localisation, because the answer is known | anything about biology — the effect was put there |
//! | [`Rung::Mechanistic`] | 27.04 | causal and experiment-design competence inside the model | anything about biology, and anything the simulator assumed |
//!
//! 27.02's own critical design decision says observed worlds are "weakest for unobserved
//! biological counterfactuals"; 27.04's says "simulator-grounded causal truth is exact only inside
//! the simulator". The ladder is not about strength. It is about which question you asked.
//!
//! # Provenance is a type, not a note
//!
//! A [`Provenance`] records the rungs a world stands on — transitively, so a semi-synthetic world
//! grafted onto a simulation stands on `{Mechanistic, SemiSynthetic}` and inherits every one of
//! the simulator's assumptions. [`support`] is the only way to obtain a [`GroundedClaim`], it takes
//! a [`Provenance`] and a [`Claim`], and it returns [`crate::error::ClaimRefusal`] when the claim
//! exceeds what the construction can carry. [`GroundedClaim`] has no public constructor and no
//! `Deserialize`, so an ungrounded claim does not typecheck as a grounded one — the device
//! `bioprism_oncoworlds::models` uses for organoid-to-patient transport, applied to a different
//! kind of distance.
//!
//! # The refusal that matters most
//!
//! [`crate::error::ClaimRefusal::AssumedByConstruction`]. 27.04's failure list names "simulator
//! encodes benchmark answer trivially" and 27.03's names "synthetic label presented as observed
//! fact". Those are the same error at two rungs: the world was built by writing down the answer,
//! and then the benchmark reports that a system found it. [`Provenance::assumptions`] is the set of
//! quantities fixed by construction, it is inherited down the ladder, and a claim naming one of
//! them is refused before any other check runs — because a circular claim is not merely
//! out-of-scope, it is void.
//!
//! The one exception is [`ClaimKind::DetectingInjectedStructure`], which is *about* the injection.
//! That claim is legitimate precisely because the ground truth was written down; the whole point
//! of 27.03 is that "robustness and failure localization have known answers".
//!
//! # What is deliberately not here
//!
//! No cohort, no simulator and no data. A [`Provenance`] is a declaration about how a world was
//! made, and this module checks declarations against each other. Nothing here can verify that a
//! world's declared provenance is true — that is 27.01's expert and exploit review, which is human
//! work, and [`crate::authoring`] records whether it happened rather than pretending to do it.

use crate::error::ClaimRefusal;
use serde::{Deserialize, Serialize};
use std::collections::BTreeSet;

/// How a world came to exist.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Rung {
    /// 27.02. Imported from real data and real workflows. Nothing in it was chosen to make a
    /// benchmark come out a particular way, and nothing in it has a known latent truth.
    Observed,
    /// 27.03. Controlled structure grafted onto an observed world. The injected part has a known
    /// answer; the rest is still whatever it was.
    SemiSynthetic,
    /// 27.04. Generated by an explicit model. Everything in it is exactly what somebody wrote
    /// down, including the parts that look like discoveries.
    Mechanistic,
}

impl Rung {
    pub const ALL: [Rung; 3] = [Rung::Observed, Rung::SemiSynthetic, Rung::Mechanistic];

    pub fn as_str(self) -> &'static str {
        match self {
            Rung::Observed => "observed",
            Rung::SemiSynthetic => "semi-synthetic",
            Rung::Mechanistic => "mechanistic",
        }
    }

    /// How many construction steps separate this rung from measurement.
    ///
    /// Reported rather than compared, because a larger distance is not worse — it is different.
    /// A mechanistic world is the only rung that can answer a question about intervention
    /// semantics, and it is the furthest from observation.
    pub fn distance_from_observation(self) -> u8 {
        match self {
            Rung::Observed => 0,
            Rung::SemiSynthetic => 1,
            Rung::Mechanistic => 2,
        }
    }
}

/// How the cohort behind an observed world was assembled — 27.02's "study design".
///
/// 27.02's failure list names "selection bias presented as world truth", and the fix is not to ban
/// selected cohorts (almost every cohort is one) but to make the selection a required declaration
/// and refuse only the claims that depend on its absence.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "selection", rename_all = "snake_case")]
pub enum Selection {
    /// Everyone meeting a stated criterion, in order. The only one of the four that supports a
    /// statement about the population the cohort was drawn from, because it is the only one whose
    /// inclusion probability does not depend on the outcome or on convenience.
    Consecutive { criterion: String },
    /// Whoever was available.
    Convenience { because: String },
    /// Deliberately over-sampled for something.
    Enriched { for_what: String },
    /// Not stated. Distinct from convenience: an undeclared selection is not known to be
    /// convenience, and guessing which it was is how a selection becomes invisible.
    Undeclared,
}

impl Selection {
    pub fn describe(&self) -> String {
        match self {
            Selection::Consecutive { criterion } => {
                format!("consecutive enrolment against `{criterion}`")
            }
            Selection::Convenience { because } => format!("convenience sampling ({because})"),
            Selection::Enriched { for_what } => format!("enrichment for `{for_what}`"),
            Selection::Undeclared => "an undeclared procedure".to_string(),
        }
    }

    fn supports_population_claim(&self) -> bool {
        matches!(self, Selection::Consecutive { .. })
    }
}

/// The rungs a world stands on and everything its construction fixed.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Provenance {
    top: Rung,
    stands_on: BTreeSet<Rung>,
    assumptions: BTreeSet<String>,
    unsupported_counterfactuals: BTreeSet<String>,
    selection: Selection,
}

impl Provenance {
    /// 27.02. A world imported from real data.
    pub fn observed(selection: Selection) -> Self {
        Provenance {
            top: Rung::Observed,
            stands_on: BTreeSet::from([Rung::Observed]),
            assumptions: BTreeSet::new(),
            unsupported_counterfactuals: BTreeSet::new(),
            selection,
        }
    }

    /// 27.04. A world generated by a simulator, whose assumptions are the quantities it fixes.
    pub fn mechanistic<I, S>(assumptions: I) -> Self
    where
        I: IntoIterator<Item = S>,
        S: Into<String>,
    {
        Provenance {
            top: Rung::Mechanistic,
            stands_on: BTreeSet::from([Rung::Mechanistic]),
            assumptions: assumptions.into_iter().map(Into::into).collect(),
            unsupported_counterfactuals: BTreeSet::new(),
            selection: Selection::Undeclared,
        }
    }

    /// 27.03. A graft onto a parent world.
    ///
    /// The parent's rungs, assumptions and unsupported counterfactuals all carry through. This is
    /// the transitivity that makes the ladder honest: grafting synthetic structure onto a
    /// simulation does not launder the simulation, and a benchmark built two steps from
    /// observation still stands two steps from observation.
    pub fn semi_synthetic<I, S>(parent: &Provenance, injected: I) -> Self
    where
        I: IntoIterator<Item = S>,
        S: Into<String>,
    {
        let mut stands_on = parent.stands_on.clone();
        stands_on.insert(Rung::SemiSynthetic);
        let mut assumptions = parent.assumptions.clone();
        assumptions.extend(injected.into_iter().map(Into::into));
        Provenance {
            top: Rung::SemiSynthetic,
            stands_on,
            assumptions,
            unsupported_counterfactuals: parent.unsupported_counterfactuals.clone(),
            selection: parent.selection.clone(),
        }
    }

    /// 27.02 workflow step 5: "declare what counterfactuals are unsupported".
    pub fn declaring_unsupported<I, S>(mut self, counterfactuals: I) -> Self
    where
        I: IntoIterator<Item = S>,
        S: Into<String>,
    {
        self.unsupported_counterfactuals
            .extend(counterfactuals.into_iter().map(Into::into));
        self
    }

    /// How this world was made, ignoring what it was made from.
    pub fn top(&self) -> Rung {
        self.top
    }

    /// Every rung in the world's ancestry, including its own.
    pub fn stands_on(&self) -> &BTreeSet<Rung> {
        &self.stands_on
    }

    /// The rung furthest from measurement anywhere in the ancestry.
    ///
    /// The number a world card should print, because it is the one that does not improve when a
    /// downstream step is added.
    pub fn furthest_from_observation(&self) -> Rung {
        self.stands_on
            .iter()
            .copied()
            .max_by_key(|r| r.distance_from_observation())
            .unwrap_or(self.top)
    }

    /// Quantities this world's construction fixed, inherited through every graft.
    pub fn assumptions(&self) -> &BTreeSet<String> {
        &self.assumptions
    }

    pub fn unsupported_counterfactuals(&self) -> &BTreeSet<String> {
        &self.unsupported_counterfactuals
    }

    pub fn selection(&self) -> &Selection {
        &self.selection
    }

    fn describe_rungs(&self) -> String {
        self.stands_on
            .iter()
            .map(|r| r.as_str())
            .collect::<Vec<_>>()
            .join(" + ")
    }
}

/// What a claim is *about*. The rungs support different kinds, and none supports all four.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ClaimKind {
    /// About the artefact as built: that a pipeline reproduces, that a workflow is deterministic,
    /// that a selection of evidence was correct given what the world contains. Every rung supports
    /// this, and it is the only kind that all three do.
    TheWorldAsBuilt,
    /// About finding or localising a change whose ground truth is known because somebody injected
    /// it. Requires a construction rung — an observed world has no injected structure, so there is
    /// nothing to have found.
    DetectingInjectedStructure,
    /// About the simulator: parameter recovery, conservation, intervention semantics. Requires
    /// [`Rung::Mechanistic`] somewhere in the ancestry, and says nothing about biology.
    SimulatorBehaviour,
    /// About biology. Requires a world standing on observation and *nothing else*.
    Biology,
}

impl ClaimKind {
    pub const ALL: [ClaimKind; 4] = [
        ClaimKind::TheWorldAsBuilt,
        ClaimKind::DetectingInjectedStructure,
        ClaimKind::SimulatorBehaviour,
        ClaimKind::Biology,
    ];

    pub fn as_str(self) -> &'static str {
        match self {
            ClaimKind::TheWorldAsBuilt => "world-as-built",
            ClaimKind::DetectingInjectedStructure => "injected-structure-detection",
            ClaimKind::SimulatorBehaviour => "simulator-behaviour",
            ClaimKind::Biology => "biological",
        }
    }

    fn requirement(self) -> &'static str {
        match self {
            ClaimKind::TheWorldAsBuilt => "any rung",
            ClaimKind::DetectingInjectedStructure => {
                "a construction rung, so that the injected structure has a known answer"
            }
            ClaimKind::SimulatorBehaviour => "a mechanistic rung",
            ClaimKind::Biology => "observation and nothing else",
        }
    }

    /// Whether a claim of this kind may name a quantity the construction fixed.
    ///
    /// Only [`ClaimKind::DetectingInjectedStructure`] may, and it is the reason 27.03 exists: the
    /// injected effect *is* the ground truth, so a claim about detecting it is grounded in the
    /// assumption rather than undermined by it.
    fn may_name_an_assumption(self) -> bool {
        matches!(self, ClaimKind::DetectingInjectedStructure)
    }

    fn satisfied_by(self, provenance: &Provenance) -> bool {
        let stands_on = provenance.stands_on();
        match self {
            ClaimKind::TheWorldAsBuilt => true,
            ClaimKind::DetectingInjectedStructure => {
                stands_on.contains(&Rung::SemiSynthetic) || stands_on.contains(&Rung::Mechanistic)
            }
            ClaimKind::SimulatorBehaviour => stands_on.contains(&Rung::Mechanistic),
            ClaimKind::Biology => *stands_on == BTreeSet::from([Rung::Observed]),
        }
    }
}

/// A statement somebody wants to make on the strength of a world.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Claim {
    pub kind: ClaimKind,
    /// The quantity the claim is about, checked against the construction's assumptions.
    pub quantity: String,
    /// The counterfactual the claim rests on, when it rests on one — "what would have happened
    /// under the other arm". Checked against 27.02's declared-unsupported list.
    pub counterfactual: Option<String>,
    /// The population the claim generalises to, when it generalises. Checked against the cohort's
    /// selection.
    pub population: Option<String>,
}

impl Claim {
    pub fn new(kind: ClaimKind, quantity: impl Into<String>) -> Self {
        Claim {
            kind,
            quantity: quantity.into(),
            counterfactual: None,
            population: None,
        }
    }

    pub fn resting_on_counterfactual(mut self, counterfactual: impl Into<String>) -> Self {
        self.counterfactual = Some(counterfactual.into());
        self
    }

    pub fn about_population(mut self, population: impl Into<String>) -> Self {
        self.population = Some(population.into());
        self
    }
}

/// A claim the world it came from can actually carry.
///
/// No public constructor, no `Deserialize`. The only route in is [`support`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct GroundedClaim {
    claim: Claim,
    stands_on: BTreeSet<Rung>,
    furthest_from_observation: Rung,
}

impl GroundedClaim {
    pub fn claim(&self) -> &Claim {
        &self.claim
    }

    pub fn stands_on(&self) -> &BTreeSet<Rung> {
        &self.stands_on
    }

    /// The sentence a methods section must contain if it quotes this claim.
    ///
    /// The same device `bioprism_scale::SimilarityRelation::treats_as_same` uses: a number or a
    /// claim that travels without the sentence that qualifies it will be read as unqualified, and
    /// generating the sentence is cheaper than hoping.
    pub fn caveat(&self) -> String {
        let rungs = self
            .stands_on
            .iter()
            .map(|r| r.as_str())
            .collect::<Vec<_>>()
            .join(" and ");
        match self.furthest_from_observation {
            Rung::Observed => format!(
                "This is a {} claim from an observed world; it is a statement about the cohort and \
                 workflow that were imported, not about any counterfactual the study design did \
                 not identify.",
                self.claim.kind.as_str()
            ),
            Rung::SemiSynthetic => format!(
                "This is a {} claim from a semi-synthetic world ({rungs}); the structure it \
                 concerns was injected, and the result measures detection of a known answer rather \
                 than a finding about biology.",
                self.claim.kind.as_str()
            ),
            Rung::Mechanistic => format!(
                "This is a {} claim from a simulated world ({rungs}); it is exact inside the model \
                 and carries no empirical biological validity.",
                self.claim.kind.as_str()
            ),
        }
    }
}

/// Ground a claim in a world's provenance, or refuse it.
///
/// The checks run in this order, and the order is the design:
///
/// 1. **Circularity.** A claim naming a quantity the construction fixed is void, not merely
///    out-of-scope, so it is caught before anything else and reported as
///    [`ClaimRefusal::AssumedByConstruction`]. Detection claims are exempt — see
///    [`ClaimKind::DetectingInjectedStructure`].
/// 2. **Rung.** Whether the ancestry contains what this kind of claim needs.
/// 3. **Counterfactual.** 27.02's declared-unsupported list.
/// 4. **Selection.** Whether the cohort supports generalising to the named population.
///
/// Running circularity first matters: a mechanistic world asked for a biological claim about a
/// quantity its simulator assumed would otherwise be refused for the vaguer reason, and the author
/// would fix the rung rather than the circularity.
pub fn support(provenance: &Provenance, claim: Claim) -> Result<GroundedClaim, ClaimRefusal> {
    if !claim.kind.may_name_an_assumption() && provenance.assumptions.contains(&claim.quantity) {
        return Err(ClaimRefusal::AssumedByConstruction {
            quantity: claim.quantity,
            assumed_by: format!("a {} construction", provenance.top.as_str()),
        });
    }
    if !claim.kind.satisfied_by(provenance) {
        return Err(ClaimRefusal::ExceedsRung {
            claim: claim.kind.as_str().to_string(),
            required: claim.kind.requirement().to_string(),
            stands_on: provenance.describe_rungs(),
        });
    }
    if let Some(counterfactual) = &claim.counterfactual {
        if provenance.unsupported_counterfactuals.contains(counterfactual) {
            return Err(ClaimRefusal::CounterfactualNotIdentified {
                counterfactual: counterfactual.clone(),
            });
        }
    }
    if let Some(population) = &claim.population {
        if !provenance.selection.supports_population_claim() {
            return Err(ClaimRefusal::SelectedCohort {
                selection: provenance.selection.describe(),
                population: population.clone(),
            });
        }
    }
    Ok(GroundedClaim {
        stands_on: provenance.stands_on.clone(),
        furthest_from_observation: provenance.furthest_from_observation(),
        claim,
    })
}
