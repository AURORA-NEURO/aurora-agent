//! Mechanistic and simulated worlds (27.04).
//!
//! A simulator gives exact causal ground truth and gives it for free, which is why 27.04 exists and
//! why its *Critical design decision* is a warning: "simulator-grounded causal truth is exact only
//! inside the simulator. The hub distinguishes simulator competence from empirical biological
//! validity." Everything in a simulated world is exactly what somebody wrote down, including the
//! parts that look like discoveries.
//!
//! This module makes three of 27.04's four failure modes checkable and says why the fourth is not:
//!
//! * **"simulator encodes benchmark answer trivially"** — [`Simulator::assumptions`] is required
//!   and non-empty, it flows into [`crate::provenance::Provenance::mechanistic`], and a claim
//!   naming one is refused as
//!   [`crate::error::ClaimRefusal::AssumedByConstruction`]. A simulator that declares no
//!   assumptions is refused outright, because a model with no stated limits produces results that
//!   read as unconditional.
//! * **"parameters chosen after model results"** — [`cite_for_result`] compares the calibration
//!   instant with the result instant and refuses a citation that runs backwards. This is the only
//!   one of the four that is a pure ordering fact, and it is the one most often lost.
//! * **"model misspecification hidden"** — [`in_envelope`] refuses a parameter outside the
//!   calibrated interval. Extrapolation is not forbidden, it is *named*: 27.04's validation list
//!   includes "out-of-calibration tests", which are valuable precisely because they are labelled.
//! * **"synthetic success marketed as biological discovery"** is not checkable here. It happens in
//!   a press release, not in a data structure. What this crate can do is make the provenance
//!   travel with the claim, which is [`crate::provenance::GroundedClaim::caveat`].
//!
//! # What is deliberately not here
//!
//! **There is no simulator.** No state transition, no sampler, no noise model, no solver, and no
//! parameter recovery. 27.04's validation list — conservation laws, parameter recovery, sensitivity
//! analysis, independent implementation comparison — is a numerical programme against a model this
//! crate does not contain, and stubbing it would produce numbers with nothing behind them. What is
//! here is the *bookkeeping around* a simulator: what it assumed, when it was calibrated, and over
//! what envelope, so that a claim drawn from it can be checked against those three things.
//!
//! Times are `bioprism_scope::Timestamp`, parsed from RFC 3339 by the caller. Nothing reads a
//! clock: a crate whose output depended on when it ran could not be replayed.

use crate::error::SimulatorRefusal;
use crate::provenance::Provenance;
use bioprism_scope::Timestamp;
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, BTreeSet};

/// The interval over which a parameter was calibrated.
///
/// Integer bounds in the parameter's own units. The blueprint fixes no units and no parameters;
/// both are the caller's, and integers keep the comparison exact across platforms.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct CalibratedInterval {
    pub low: i64,
    pub high: i64,
}

impl CalibratedInterval {
    pub fn new(low: i64, high: i64) -> Self {
        CalibratedInterval {
            low: low.min(high),
            high: low.max(high),
        }
    }

    pub fn contains(&self, value: i64) -> bool {
        self.low <= value && value <= self.high
    }
}

/// A declared model — 27.04's "simulator source", "parameter priors", "calibration targets" and
/// "model-limit card", reduced to the parts a type can check.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Simulator {
    id: String,
    assumptions: BTreeSet<String>,
    calibrated_at: Timestamp,
    envelope: BTreeMap<String, CalibratedInterval>,
}

impl Simulator {
    pub fn id(&self) -> &str {
        &self.id
    }

    /// The quantities this model fixes rather than derives.
    ///
    /// 27.04's "model-limit card" in the form the rest of the crate can use. Every one of these
    /// becomes a quantity the resulting world cannot be evidence *for*.
    pub fn assumptions(&self) -> &BTreeSet<String> {
        &self.assumptions
    }

    pub fn calibrated_at(&self) -> Timestamp {
        self.calibrated_at
    }

    pub fn envelope(&self) -> &BTreeMap<String, CalibratedInterval> {
        &self.envelope
    }

    /// The provenance a world generated by this simulator stands on.
    pub fn provenance(&self) -> Provenance {
        Provenance::mechanistic(self.assumptions.iter().cloned())
    }
}

/// Declare a simulator, refusing one with no stated assumptions.
///
/// The empty-assumption refusal is the load-bearing one. Every model assumes something; a model
/// whose author cannot name one thing it assumes has not examined it, and every claim drawn from it
/// will be unbounded by construction.
pub fn declare_simulator<I, S>(
    id: impl Into<String>,
    assumptions: I,
    calibrated_at: Timestamp,
    envelope: BTreeMap<String, CalibratedInterval>,
) -> Result<Simulator, SimulatorRefusal>
where
    I: IntoIterator<Item = S>,
    S: Into<String>,
{
    let id = id.into();
    let assumptions: BTreeSet<String> = assumptions.into_iter().map(Into::into).collect();
    if assumptions.is_empty() {
        return Err(SimulatorRefusal::NoDeclaredAssumptions { simulator: id });
    }
    Ok(Simulator {
        id,
        assumptions,
        calibrated_at,
        envelope,
    })
}

/// Refuse a citation whose calibration postdates the result it supports.
///
/// 27.04's failure "parameters chosen after model results". A model tuned after seeing the number
/// it is cited for has been fitted to that number, and the recovery tests it passed afterwards
/// measure the fit rather than the model.
pub fn cite_for_result(
    simulator: &Simulator,
    result_at: Timestamp,
) -> Result<(), SimulatorRefusal> {
    if simulator.calibrated_at > result_at {
        return Err(SimulatorRefusal::CalibratedAfterResult {
            simulator: simulator.id.clone(),
            calibrated_at: simulator.calibrated_at.to_rfc3339(),
            result_at: result_at.to_rfc3339(),
        });
    }
    Ok(())
}

/// Refuse a parameter setting the model was never calibrated over.
///
/// A parameter with no declared interval is *not* an error here: an undeclared envelope dimension
/// is a gap in the model-limit card, and reporting it as out-of-calibration would conflate "we
/// checked and it is outside" with "nobody said". Use [`uncalibrated_parameters`] for the second.
pub fn in_envelope(
    simulator: &Simulator,
    parameters: &BTreeMap<String, i64>,
) -> Result<(), SimulatorRefusal> {
    for (name, value) in parameters {
        if let Some(interval) = simulator.envelope.get(name) {
            if !interval.contains(*value) {
                return Err(SimulatorRefusal::OutOfCalibration {
                    parameter: name.clone(),
                    value: value.to_string(),
                    low: interval.low.to_string(),
                    high: interval.high.to_string(),
                });
            }
        }
    }
    Ok(())
}

/// Parameters the caller set that the simulator's envelope says nothing about.
///
/// Returned rather than refused, because "the model-limit card is silent here" is a finding about
/// the card and an author should be able to publish a world with it recorded.
pub fn uncalibrated_parameters(
    simulator: &Simulator,
    parameters: &BTreeMap<String, i64>,
) -> BTreeSet<String> {
    parameters
        .keys()
        .filter(|name| !simulator.envelope.contains_key(*name))
        .cloned()
        .collect()
}
