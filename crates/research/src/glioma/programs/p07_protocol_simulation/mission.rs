//! Science-aware autonomous mission control for preclinical glioma research.
//!
//! The existing action and campaign executors are deliberately general.  This module adds the
//! missing product layer: a mission controller that repeatedly chooses the next *scientific
//! frontier* across evidence, mechanism, assay, computation, and replication actions.  It
//! updates a small deterministic belief state from returned typed outcomes, rewards uncovered
//! stages and model/modality pairs, and uses negative or contradictory results to redirect the
//! next round.  The controller never invents observations and never treats a dry-run artifact as
//! biological evidence; a local institution supplies the executor for real work.

use super::action_execution::{
    execute_glioma_action_portfolio, ActionPortfolioExecution, ActionPortfolioExecutionDisposition,
    ActionPortfolioExecutionError, ActionPortfolioExecutionRequest, GliomaActionExecutor,
    MAX_RETRIES,
};
use crate::glioma_engine::{
    GliomaActionCandidate, GliomaActionSelection, GliomaModality, GliomaModelSystem,
    GliomaSelectionConfig, GliomaStageKind,
};
use bioprism_ids::ContentHash;
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, BTreeSet};
use thiserror::Error;

pub const FEATURE_ID: &str = "GAF-GLIOMA-P07-F31";
pub const OUTPUT_SCHEMA: &str = "GliomaAutonomousResearchMission1@1";
pub const MAX_ROUNDS: u16 = 64;
pub const MAX_CANDIDATES: usize = 256;

/// Gates that turn a stream of locally executed results into a qualified mission.  A gate is
/// never inferred from model confidence alone: stage coverage, information gain, and uncertainty
/// are explicit and remain inspectable in the output.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct GliomaMissionGates {
    pub required_stages: BTreeSet<GliomaStageKind>,
    pub min_completed_actions: u16,
    pub min_information_gain_milli: u32,
    pub max_uncertainty_milli: u32,
    pub min_model_systems: u8,
    pub min_modalities: u8,
}

impl Default for GliomaMissionGates {
    fn default() -> Self {
        Self {
            required_stages: BTreeSet::from([GliomaStageKind::MechanismExploration]),
            min_completed_actions: 1,
            min_information_gain_milli: 500,
            max_uncertainty_milli: 10_000,
            min_model_systems: 1,
            min_modalities: 1,
        }
    }
}

/// A bounded multi-round mission over typed local actions.  Candidates may be generated by the
/// evidence, mechanism, experiment-design, computation, or replication programs; the mission
/// controller is the cross-program scientific scheduler, not a replacement for those analyzers.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct GliomaMissionRequest {
    pub mission_id: String,
    pub objective: String,
    pub candidates: Vec<GliomaActionCandidate>,
    pub completed_action_order: Vec<String>,
    pub selection: GliomaSelectionConfig,
    pub gates: GliomaMissionGates,
    pub max_rounds: u16,
    pub max_retries: u8,
    pub require_artifacts: bool,
    pub stop_on_negative: bool,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum GliomaMissionDisposition {
    Qualified,
    Partial,
    Negative,
    Blocked,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum GliomaMissionStopReason {
    Qualified,
    NegativeEvidence,
    NoRunnableActions,
    BudgetExhausted,
    MaxRounds,
    NoProgress,
    ExecutorFailed,
    SafetyBlocked,
}

/// One closed-loop planning/execution cycle.  `selection` contains the complete candidate
/// partition and `execution` contains the typed result for every selected action, so a caller can
/// render a researcher-facing rationale without recomputing the controller's choices.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct GliomaMissionRound {
    pub round: u16,
    pub planner_note: String,
    pub selection: GliomaActionSelection,
    pub execution: ActionPortfolioExecution,
    pub cost_units: u32,
    pub budget_before_units: u32,
    pub budget_after_units: u32,
    pub information_gain_milli: u32,
    pub uncertainty_milli: u32,
    pub stage_coverage: Vec<GliomaStageKind>,
    pub model_system_coverage: Vec<GliomaModelSystem>,
    pub modality_coverage: Vec<GliomaModality>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct GliomaAutonomousResearchMission {
    pub feature_id: String,
    pub output_schema: String,
    pub mission_id: String,
    pub objective: String,
    pub rounds: Vec<GliomaMissionRound>,
    pub completed_action_order: Vec<String>,
    pub negative_action_order: Vec<String>,
    pub failed_action_order: Vec<String>,
    pub retry_count: u32,
    pub budget_spent_units: u32,
    pub remaining_budget_units: u32,
    pub information_gain_milli: u32,
    pub uncertainty_milli: u32,
    pub stage_coverage: Vec<GliomaStageKind>,
    pub model_system_coverage: Vec<GliomaModelSystem>,
    pub modality_coverage: Vec<GliomaModality>,
    pub unresolved_order: Vec<String>,
    pub negative_evidence: Vec<String>,
    pub uncertainty: Vec<String>,
    pub disposition: GliomaMissionDisposition,
    pub stop_reason: GliomaMissionStopReason,
    pub digest: ContentHash,
}

#[derive(Debug, Error, PartialEq, Eq)]
pub enum GliomaMissionError {
    #[error("glioma mission request is invalid: {0}")]
    InvalidRequest(String),
    #[error("glioma mission execution failed: {0}")]
    Execution(String),
    #[error("glioma mission output is invalid: {0}")]
    InvalidOutput(String),
    #[error("glioma mission digest failed: {0}")]
    Digest(String),
}

fn canonical<T: Ord>(values: &[T]) -> bool {
    values.windows(2).all(|pair| pair[0] < pair[1])
}

fn unique_strings(values: &[String]) -> bool {
    values.iter().all(|value| !value.trim().is_empty())
        && values.windows(2).all(|pair| pair[0] < pair[1])
}

fn digest_input(mission: &GliomaAutonomousResearchMission) -> serde_json::Value {
    serde_json::json!({
        "feature_id": mission.feature_id,
        "output_schema": mission.output_schema,
        "mission_id": mission.mission_id,
        "objective": mission.objective,
        "rounds": mission.rounds,
        "completed_action_order": mission.completed_action_order,
        "negative_action_order": mission.negative_action_order,
        "failed_action_order": mission.failed_action_order,
        "retry_count": mission.retry_count,
        "budget_spent_units": mission.budget_spent_units,
        "remaining_budget_units": mission.remaining_budget_units,
        "information_gain_milli": mission.information_gain_milli,
        "uncertainty_milli": mission.uncertainty_milli,
        "stage_coverage": mission.stage_coverage,
        "model_system_coverage": mission.model_system_coverage,
        "modality_coverage": mission.modality_coverage,
        "unresolved_order": mission.unresolved_order,
        "negative_evidence": mission.negative_evidence,
        "uncertainty": mission.uncertainty,
        "disposition": mission.disposition,
        "stop_reason": mission.stop_reason,
    })
}

impl GliomaAutonomousResearchMission {
    pub fn validate(&self) -> Result<(), GliomaMissionError> {
        if self.feature_id != FEATURE_ID
            || self.output_schema != OUTPUT_SCHEMA
            || self.mission_id.trim().is_empty()
            || self.objective.trim().is_empty()
            || self.rounds.len() > MAX_ROUNDS as usize
            || !unique_strings(&self.completed_action_order)
            || !unique_strings(&self.negative_action_order)
            || !unique_strings(&self.failed_action_order)
            || !unique_strings(&self.unresolved_order)
            || !unique_strings(&self.negative_evidence)
            || !unique_strings(&self.uncertainty)
            || !canonical(&self.stage_coverage)
            || !canonical(&self.model_system_coverage)
            || !canonical(&self.modality_coverage)
            || self
                .completed_action_order
                .iter()
                .any(|id| self.negative_action_order.binary_search(id).is_ok())
            || self
                .failed_action_order
                .iter()
                .any(|id| self.completed_action_order.binary_search(id).is_ok())
        {
            return Err(GliomaMissionError::InvalidOutput(
                "mission identity, canonical partitions, coverage, or evidence fields are invalid"
                    .into(),
            ));
        }
        let mut seen_rounds = BTreeSet::new();
        let mut seen_actions = BTreeSet::new();
        let mut expected_spend = 0_u32;
        let mut expected_retry = 0_u32;
        for round in &self.rounds {
            if round.round == 0
                || !seen_rounds.insert(round.round)
                || round.planner_note.trim().is_empty()
                || round.selection.selected_order != round.execution.action_order
                || round.budget_after_units > round.budget_before_units
                || round.cost_units
                    != round
                        .budget_before_units
                        .saturating_sub(round.budget_after_units)
                || !canonical(&round.stage_coverage)
                || !canonical(&round.model_system_coverage)
                || !canonical(&round.modality_coverage)
            {
                return Err(GliomaMissionError::InvalidOutput(
                    "mission round ordering, budget, selection, or coverage is invalid".into(),
                ));
            }
            round
                .execution
                .validate()
                .map_err(|error| GliomaMissionError::InvalidOutput(error.to_string()))?;
            for action_id in &round.execution.action_order {
                if !seen_actions.insert(action_id.clone()) {
                    return Err(GliomaMissionError::InvalidOutput(
                        "an action was executed more than once across mission rounds".into(),
                    ));
                }
            }
            expected_spend = expected_spend.saturating_add(round.cost_units);
            expected_retry = expected_retry.saturating_add(round.execution.retry_count);
        }
        if expected_spend != self.budget_spent_units || expected_retry != self.retry_count {
            return Err(GliomaMissionError::InvalidOutput(
                "mission budget or retry totals do not reconcile with rounds".into(),
            ));
        }
        let expected = ContentHash::of_value(&digest_input(self))
            .map_err(|error| GliomaMissionError::Digest(error.to_string()))?;
        if expected != self.digest {
            return Err(GliomaMissionError::InvalidOutput(
                "mission digest is not content-addressed".into(),
            ));
        }
        Ok(())
    }
}

fn validate_request(request: &GliomaMissionRequest) -> Result<(), GliomaMissionError> {
    if request.mission_id.trim().is_empty()
        || request.objective.trim().is_empty()
        || request.candidates.is_empty()
        || request.candidates.len() > MAX_CANDIDATES
        || request.max_rounds == 0
        || request.max_rounds > MAX_ROUNDS
        || request.max_retries > MAX_RETRIES
        || request.selection.budget_units == 0
        || request.selection.max_actions == 0
        || request
            .completed_action_order
            .iter()
            .any(|id| id.trim().is_empty())
        || !request
            .completed_action_order
            .windows(2)
            .all(|pair| pair[0] < pair[1])
        || request.gates.min_model_systems == 0
        || request.gates.min_modalities == 0
        || request
            .gates
            .required_stages
            .iter()
            .any(|stage| *stage == GliomaStageKind::IntentNormalization)
    {
        return Err(GliomaMissionError::InvalidRequest(
            "mission identity, bounded candidates/rounds/retries, positive gates, and canonical completed actions are required"
                .into(),
        ));
    }
    // This validates every candidate, dependency, effect, and selection permission before any
    // local executor can be called.  The returned selection is intentionally discarded.
    crate::glioma_engine::select_glioma_actions(
        &request.candidates,
        &request.completed_action_order.iter().cloned().collect(),
        &request.selection,
    )
    .map_err(|error| GliomaMissionError::InvalidRequest(error.to_string()))?;
    Ok(())
}

fn bounded_score(value: u16, delta: i32) -> u16 {
    (i32::from(value) + delta).clamp(0, 1_000) as u16
}

fn adjust_candidates(
    candidates: &[GliomaActionCandidate],
    completed: &BTreeSet<String>,
    negative: &BTreeSet<String>,
    uncertainty_milli: u32,
) -> Vec<GliomaActionCandidate> {
    let completed_pairs = candidates
        .iter()
        .filter(|candidate| completed.contains(&candidate.action_id))
        .map(|candidate| (candidate.modality, candidate.model_system))
        .collect::<BTreeSet<_>>();
    let completed_stages = candidates
        .iter()
        .filter(|candidate| completed.contains(&candidate.action_id))
        .map(|candidate| candidate.stage_kind)
        .collect::<BTreeSet<_>>();
    candidates
        .iter()
        .map(|candidate| {
            let mut adjusted = candidate.clone();
            let uncovered_stage = !completed_stages.contains(&candidate.stage_kind);
            let novel_pair =
                !completed_pairs.contains(&(candidate.modality, candidate.model_system));
            let resolves_negative_dependency = candidate
                .depends_on
                .iter()
                .any(|dependency| negative.contains(dependency));
            let uncertainty_pressure = (uncertainty_milli / 100).min(180) as i32;
            let stage_delta = if uncovered_stage { 140 } else { -30 };
            let diversity_delta = if novel_pair { 120 } else { -80 };
            let contradiction_delta = if resolves_negative_dependency { 160 } else { 0 };
            adjusted.information_gain_milli = bounded_score(
                adjusted.information_gain_milli,
                stage_delta + diversity_delta + contradiction_delta + uncertainty_pressure,
            );
            adjusted.frontier_novelty_milli = bounded_score(
                adjusted.frontier_novelty_milli,
                if uncovered_stage { 100 } else { -20 } + if novel_pair { 100 } else { -40 },
            );
            adjusted.cross_stage_unlock_milli = bounded_score(
                adjusted.cross_stage_unlock_milli,
                if uncovered_stage { 120 } else { 0 }
                    + if resolves_negative_dependency { 80 } else { 0 },
            );
            adjusted.reproducibility_safety_milli = bounded_score(
                adjusted.reproducibility_safety_milli,
                if uncertainty_milli > 0 { 70 } else { 0 },
            );
            adjusted
        })
        .collect()
}

fn coverage(
    candidates: &[GliomaActionCandidate],
    completed: &BTreeSet<String>,
) -> (
    Vec<GliomaStageKind>,
    Vec<GliomaModelSystem>,
    Vec<GliomaModality>,
) {
    let mut stages = BTreeSet::new();
    let mut models = BTreeSet::new();
    let mut modalities = BTreeSet::new();
    for candidate in candidates {
        if completed.contains(&candidate.action_id) {
            stages.insert(candidate.stage_kind);
            models.insert(candidate.model_system);
            modalities.insert(candidate.modality);
        }
    }
    (
        stages.into_iter().collect(),
        models.into_iter().collect(),
        modalities.into_iter().collect(),
    )
}

fn gates_satisfied(
    request: &GliomaMissionRequest,
    completed: &BTreeSet<String>,
    negative: &BTreeSet<String>,
    information_gain_milli: u32,
    uncertainty_milli: u32,
    candidates: &[GliomaActionCandidate],
) -> bool {
    let positive_completed = completed
        .difference(negative)
        .cloned()
        .collect::<BTreeSet<_>>();
    let (stages, models, modalities) = coverage(candidates, &positive_completed);
    request
        .gates
        .required_stages
        .iter()
        .all(|stage| stages.contains(stage))
        && positive_completed.len() >= usize::from(request.gates.min_completed_actions)
        && information_gain_milli >= request.gates.min_information_gain_milli
        && uncertainty_milli <= request.gates.max_uncertainty_milli
        && models.len() >= usize::from(request.gates.min_model_systems)
        && modalities.len() >= usize::from(request.gates.min_modalities)
}

fn planner_note(
    candidates: &[GliomaActionCandidate],
    completed: &BTreeSet<String>,
    negative: &BTreeSet<String>,
    uncertainty_milli: u32,
) -> String {
    let (stages, models, modalities) = coverage(candidates, completed);
    format!(
        "adaptive frontier: {} stages, {} model systems, {} modalities covered; {} negative actions and {} uncertainty milli; prioritizing uncovered and contradiction-resolving candidates",
        stages.len(),
        models.len(),
        modalities.len(),
        negative.len(),
        uncertainty_milli
    )
}

/// Execute a science-aware, bounded autonomous mission.  Every round is replanned from the
/// returned typed action results, so an institution can resume by passing the completed and
/// negative action partitions from the prior output.  Failed or partial effects terminate the
/// mission; they are never silently retried as if they were scientific evidence.
pub fn execute_glioma_autonomous_research_mission<E: GliomaActionExecutor>(
    request: &GliomaMissionRequest,
    executor: &mut E,
) -> Result<GliomaAutonomousResearchMission, GliomaMissionError> {
    validate_request(request)?;
    let mut completed = request
        .completed_action_order
        .iter()
        .cloned()
        .collect::<BTreeSet<_>>();
    let mut negative = BTreeSet::new();
    let mut failed = BTreeSet::new();
    let mut retired = completed.clone();
    let mut rounds = Vec::new();
    let mut negative_evidence = BTreeSet::new();
    let mut uncertainty = BTreeSet::new();
    let mut information_gain_milli = 0_u32;
    let mut uncertainty_milli = 0_u32;
    let mut budget_spent_units = 0_u32;
    let mut retry_count = 0_u32;
    let mut stop_reason = GliomaMissionStopReason::MaxRounds;

    for round_number in 1..=request.max_rounds {
        if gates_satisfied(
            request,
            &completed,
            &negative,
            information_gain_milli,
            uncertainty_milli,
            &request.candidates,
        ) {
            stop_reason = GliomaMissionStopReason::Qualified;
            break;
        }
        let remaining_budget = request
            .selection
            .budget_units
            .saturating_sub(budget_spent_units);
        if remaining_budget == 0 {
            stop_reason = GliomaMissionStopReason::BudgetExhausted;
            break;
        }
        let active = request
            .candidates
            .iter()
            .filter(|candidate| !retired.contains(&candidate.action_id))
            .cloned()
            .collect::<Vec<_>>();
        if active.is_empty() {
            stop_reason = if gates_satisfied(
                request,
                &completed,
                &negative,
                information_gain_milli,
                uncertainty_milli,
                &request.candidates,
            ) {
                GliomaMissionStopReason::Qualified
            } else if !negative.is_empty() {
                GliomaMissionStopReason::NegativeEvidence
            } else {
                GliomaMissionStopReason::NoRunnableActions
            };
            break;
        }
        let adjusted = adjust_candidates(&active, &completed, &negative, uncertainty_milli);
        let mut selection_config = request.selection.clone();
        selection_config.budget_units = remaining_budget;
        let selection =
            crate::glioma_engine::select_glioma_actions(&adjusted, &completed, &selection_config)
                .map_err(|error| GliomaMissionError::Execution(error.to_string()))?;
        if selection.selected_order.is_empty() {
            stop_reason = if gates_satisfied(
                request,
                &completed,
                &negative,
                information_gain_milli,
                uncertainty_milli,
                &request.candidates,
            ) {
                GliomaMissionStopReason::Qualified
            } else {
                GliomaMissionStopReason::NoRunnableActions
            };
            break;
        }
        let cost_by_id = adjusted
            .iter()
            .map(|candidate| (candidate.action_id.clone(), candidate.cost_units))
            .collect::<BTreeMap<_, _>>();
        let round_cost = selection
            .selected_order
            .iter()
            .map(|id| cost_by_id.get(id).copied().unwrap_or(0))
            .sum::<u32>();
        let execution = execute_glioma_action_portfolio(
            &ActionPortfolioExecutionRequest {
                candidates: adjusted.clone(),
                completed_actions: completed.clone(),
                selection: selection_config,
                max_retries: request.max_retries,
                require_artifacts: request.require_artifacts,
            },
            executor,
        )
        .map_err(|error: ActionPortfolioExecutionError| {
            GliomaMissionError::Execution(error.to_string())
        })?;
        if execution.action_order != selection.selected_order {
            return Err(GliomaMissionError::Execution(
                "mission selector changed between planning and execution".into(),
            ));
        }
        let before_budget = request
            .selection
            .budget_units
            .saturating_sub(budget_spent_units);
        budget_spent_units = budget_spent_units.saturating_add(round_cost);
        retry_count = retry_count.saturating_add(execution.retry_count);
        let prior_completed = completed.clone();
        for action_id in &execution.completed_order {
            completed.insert(action_id.clone());
            retired.insert(action_id.clone());
        }
        for action_id in &execution.negative_order {
            completed.insert(action_id.clone());
            negative.insert(action_id.clone());
            retired.insert(action_id.clone());
        }
        for action_id in &execution.failed_order {
            failed.insert(action_id.clone());
            retired.insert(action_id.clone());
        }
        for result in &execution.results {
            negative_evidence.extend(result.negative_evidence.iter().cloned());
            uncertainty.extend(result.uncertainty.iter().cloned());
        }
        let newly_completed = completed.difference(&prior_completed).count();
        information_gain_milli = information_gain_milli.saturating_add(
            execution
                .completed_order
                .iter()
                .chain(execution.negative_order.iter())
                .filter_map(|id| cost_by_id.get(id).map(|_| id))
                .map(|id| {
                    adjusted
                        .iter()
                        .find(|candidate| &candidate.action_id == id)
                        .map(|candidate| u32::from(candidate.information_gain_milli))
                        .unwrap_or(0)
                })
                .sum::<u32>(),
        );
        uncertainty_milli = (uncertainty.len() as u32).saturating_mul(100);
        let (stage_coverage, model_system_coverage, modality_coverage) =
            coverage(&request.candidates, &completed);
        let after_budget = request
            .selection
            .budget_units
            .saturating_sub(budget_spent_units);
        rounds.push(GliomaMissionRound {
            round: round_number,
            planner_note: planner_note(
                &request.candidates,
                &completed,
                &negative,
                uncertainty_milli,
            ),
            selection,
            execution: execution.clone(),
            cost_units: round_cost,
            budget_before_units: before_budget,
            budget_after_units: after_budget,
            information_gain_milli,
            uncertainty_milli,
            stage_coverage,
            model_system_coverage,
            modality_coverage,
        });
        if request.stop_on_negative && !execution.negative_order.is_empty() {
            stop_reason = GliomaMissionStopReason::NegativeEvidence;
            break;
        }
        match execution.disposition {
            ActionPortfolioExecutionDisposition::Failed => {
                stop_reason = GliomaMissionStopReason::ExecutorFailed;
                break;
            }
            ActionPortfolioExecutionDisposition::Partial => {
                stop_reason = GliomaMissionStopReason::SafetyBlocked;
                break;
            }
            ActionPortfolioExecutionDisposition::Blocked => {
                stop_reason = GliomaMissionStopReason::SafetyBlocked;
                break;
            }
            ActionPortfolioExecutionDisposition::Completed => {}
        }
        if newly_completed == 0 {
            stop_reason = GliomaMissionStopReason::NoProgress;
            break;
        }
        if after_budget == 0 {
            stop_reason = GliomaMissionStopReason::BudgetExhausted;
            break;
        }
    }

    let (stage_coverage, model_system_coverage, modality_coverage) =
        coverage(&request.candidates, &completed);
    let disposition = if gates_satisfied(
        request,
        &completed,
        &negative,
        information_gain_milli,
        uncertainty_milli,
        &request.candidates,
    ) {
        GliomaMissionDisposition::Qualified
    } else if !failed.is_empty() || matches!(stop_reason, GliomaMissionStopReason::SafetyBlocked) {
        GliomaMissionDisposition::Blocked
    } else if !negative.is_empty() && completed.len() == negative.len() {
        GliomaMissionDisposition::Negative
    } else if rounds.is_empty() {
        GliomaMissionDisposition::Blocked
    } else {
        GliomaMissionDisposition::Partial
    };
    let positive_completed_order = completed
        .iter()
        .filter(|action_id| !negative.contains(*action_id))
        .cloned()
        .collect::<Vec<_>>();
    let negative_action_order = negative.iter().cloned().collect::<Vec<_>>();
    let failed_action_order = failed.iter().cloned().collect::<Vec<_>>();
    let mut output = GliomaAutonomousResearchMission {
        feature_id: FEATURE_ID.into(),
        output_schema: OUTPUT_SCHEMA.into(),
        mission_id: request.mission_id.clone(),
        objective: request.objective.clone(),
        rounds,
        completed_action_order: positive_completed_order,
        negative_action_order,
        failed_action_order,
        retry_count,
        budget_spent_units,
        remaining_budget_units: request
            .selection
            .budget_units
            .saturating_sub(budget_spent_units),
        information_gain_milli,
        uncertainty_milli,
        stage_coverage,
        model_system_coverage,
        modality_coverage,
        unresolved_order: request
            .candidates
            .iter()
            .filter(|candidate| {
                !completed.contains(&candidate.action_id) && !failed.contains(&candidate.action_id)
            })
            .map(|candidate| candidate.action_id.clone())
            .collect(),
        negative_evidence: negative_evidence.into_iter().collect(),
        uncertainty: uncertainty.into_iter().collect(),
        disposition,
        stop_reason,
        digest: ContentHash::of_bytes(b"unsealed-glioma-autonomous-research-mission"),
    };
    output.digest = ContentHash::of_value(&digest_input(&output))
        .map_err(|error| GliomaMissionError::Digest(error.to_string()))?;
    output.validate()?;
    Ok(output)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::glioma::programs::p07_protocol_simulation::DryRunGliomaActionExecutor;
    use bioprism_foundation::{AutonomyTier, Effect};

    fn candidate(
        id: &str,
        stage_kind: GliomaStageKind,
        modality: GliomaModality,
        model_system: GliomaModelSystem,
        information_gain_milli: u16,
    ) -> GliomaActionCandidate {
        GliomaActionCandidate {
            action_id: id.into(),
            stage_kind,
            modality,
            model_system,
            depends_on: Vec::new(),
            cost_units: 2,
            information_gain_milli,
            frontier_novelty_milli: 700,
            workflow_leverage_milli: 600,
            cross_stage_unlock_milli: 500,
            reproducibility_safety_milli: 900,
            federation_value_milli: 0,
            feasibility_milli: 900,
            autonomy_tier: AutonomyTier::A1,
            effects: BTreeSet::from([
                Effect::ReadLocalData,
                Effect::ExecuteLocalComputation,
                Effect::WriteLocalArtifact,
            ]),
        }
    }

    fn request(candidates: Vec<GliomaActionCandidate>) -> GliomaMissionRequest {
        GliomaMissionRequest {
            mission_id: "mission-glioma-invasion".into(),
            objective: "resolve invasion mechanism across models".into(),
            candidates,
            completed_action_order: Vec::new(),
            selection: GliomaSelectionConfig {
                budget_units: 8,
                max_actions: 1,
                ..GliomaSelectionConfig::default()
            },
            gates: GliomaMissionGates {
                required_stages: BTreeSet::from([GliomaStageKind::MechanismExploration]),
                min_completed_actions: 1,
                min_information_gain_milli: 400,
                max_uncertainty_milli: 10_000,
                min_model_systems: 1,
                min_modalities: 1,
            },
            max_rounds: 4,
            max_retries: 1,
            require_artifacts: true,
            stop_on_negative: false,
        }
    }

    #[test]
    fn mission_reaches_scientific_gate_and_is_replayable() {
        let candidates = vec![candidate(
            "mechanism-organoid",
            GliomaStageKind::MechanismExploration,
            GliomaModality::Transcriptomics,
            GliomaModelSystem::Organoid,
            900,
        )];
        let request = request(candidates);
        let mut executor = DryRunGliomaActionExecutor;
        let mission = execute_glioma_autonomous_research_mission(&request, &mut executor).unwrap();
        assert_eq!(mission.disposition, GliomaMissionDisposition::Qualified);
        assert_eq!(mission.stop_reason, GliomaMissionStopReason::Qualified);
        assert_eq!(mission.completed_action_order, vec!["mechanism-organoid"]);
        assert_eq!(mission.rounds.len(), 1);
        mission.validate().unwrap();
    }

    #[test]
    fn mission_preserves_negative_results_and_redirects_to_new_model() {
        let first = candidate(
            "mechanism-organoid",
            GliomaStageKind::MechanismExploration,
            GliomaModality::Transcriptomics,
            GliomaModelSystem::Organoid,
            650,
        );
        let second = candidate(
            "mechanism-mouse",
            GliomaStageKind::MechanismExploration,
            GliomaModality::Imaging,
            GliomaModelSystem::MouseModel,
            200,
        );
        struct NegativeFirst {
            calls: u8,
        }
        impl GliomaActionExecutor for NegativeFirst {
            fn execute_action(
                &mut self,
                candidate: &GliomaActionCandidate,
                attempt: u8,
            ) -> Result<
                super::super::action_execution::ActionExecutionResult,
                super::super::action_execution::ActionExecutionFailure,
            > {
                self.calls = self.calls.saturating_add(1);
                let hash = ContentHash::of_value(&serde_json::json!({
                    "candidate": candidate.action_id,
                    "attempt": attempt,
                }))
                .unwrap();
                Ok(super::super::action_execution::ActionExecutionResult {
                    action_id: candidate.action_id.clone(),
                    disposition: if self.calls == 1 {
                        super::super::action_execution::ActionExecutionDisposition::Negative
                    } else {
                        super::super::action_execution::ActionExecutionDisposition::Completed
                    },
                    attempt_count: attempt,
                    artifact: Some(crate::glioma_engine::LocalArtifactRef {
                        artifact_id: format!("artifact:{}", candidate.action_id),
                        content_hash: hash,
                        content_type: "application/json".into(),
                        local_only: true,
                        contains_human_data: false,
                        contains_direct_identifiers: false,
                    }),
                    note: "typed local outcome".into(),
                    uncertainty: vec!["alternative-model-needed".into()],
                    negative_evidence: vec!["no-effect-in-first-model".into()],
                })
            }
        }
        let mut executor = NegativeFirst { calls: 0 };
        let mission = execute_glioma_autonomous_research_mission(
            &request(vec![first, second]),
            &mut executor,
        )
        .unwrap();
        assert_eq!(mission.negative_action_order, vec!["mechanism-organoid"]);
        assert_eq!(mission.completed_action_order, vec!["mechanism-mouse"]);
        assert_eq!(mission.model_system_coverage.len(), 2);
        assert_eq!(mission.rounds.len(), 2);
        mission.validate().unwrap();
    }

    #[test]
    fn mission_does_not_execute_when_policy_blocks_all_actions() {
        let mut blocked = candidate(
            "instrument-preflight",
            GliomaStageKind::InstrumentPreflight,
            GliomaModality::Instrument,
            GliomaModelSystem::Organoid,
            900,
        );
        blocked.autonomy_tier = AutonomyTier::A3;
        let mut request = request(vec![blocked]);
        request.selection.max_actions = 1;
        let mut executor = DryRunGliomaActionExecutor;
        let mission = execute_glioma_autonomous_research_mission(&request, &mut executor).unwrap();
        assert!(mission.rounds.is_empty());
        assert_eq!(mission.disposition, GliomaMissionDisposition::Blocked);
        assert_eq!(
            mission.stop_reason,
            GliomaMissionStopReason::NoRunnableActions
        );
        mission.validate().unwrap();
    }
}
