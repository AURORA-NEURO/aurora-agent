#[derive(Debug, Error, PartialEq, Eq)]
pub enum GliomaMissionError {
    #[error("glioma mission request is invalid: {0}")]
    InvalidRequest(String),
    #[error("glioma mission execution failed: {0}")]
    Execution(String),
    #[error("glioma mission output is invalid: {0}")]
    InvalidOutput(String),
    #[error("glioma mission digest failed: {0}")]
    Digest(String),
}

fn canonical<T: Ord>(values: &[T]) -> bool {
    values.windows(2).all(|pair| pair[0] < pair[1])
}

fn unique_strings(values: &[String]) -> bool {
    values.iter().all(|value| !value.trim().is_empty())
        && values.windows(2).all(|pair| pair[0] < pair[1])
}

