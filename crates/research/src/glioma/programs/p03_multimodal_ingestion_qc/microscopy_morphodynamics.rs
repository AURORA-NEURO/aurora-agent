//! Local, replicate-held-out glioma cell morphodynamics for adaptive microscopy.
//!
//! The analysis converts institution-local segmented cell tracks into speed, persistence,
//! invasion-axis alignment, and shape descriptors. A unit-balanced robust nearest-prototype
//! model is calibrated by leave-one-biological-unit-out predictions; its posterior and empirical
//! outcome likelihoods can drive the P08 dose-aware acquisition loop. Phenotype names remain
//! researcher-defined, raw imagery stays local, and no model scores human-origin material.

