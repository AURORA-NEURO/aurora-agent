#[serde(rename_all = "snake_case")]
pub enum GliomaMicroscopyMaterial {
    MurineCellLine,
    MurineOrganoid,
    MouseModel,
    ZebrafishModel,
}

impl GliomaMicroscopyMaterial {
    pub const fn model_system(self) -> GliomaModelSystem {
        match self {
            Self::MurineCellLine => GliomaModelSystem::CellLine,
            Self::MurineOrganoid => GliomaModelSystem::Organoid,
            Self::MouseModel => GliomaModelSystem::MouseModel,
            Self::ZebrafishModel => GliomaModelSystem::ZebrafishModel,
        }
    }
}

