fn invalid_field(reason: impl Into<String>) -> MicroscopyMorphodynamicError {
    MicroscopyMorphodynamicError::InvalidField(reason.into())
}

fn validate_field(field: &MicroscopyFieldInput) -> Result<(), MicroscopyMorphodynamicError> {
    if field.field_id.trim().is_empty()
        || field.region_id.trim().is_empty()
        || field.independent_unit_id.trim().is_empty()
        || field.biological_stratum.trim().is_empty()
        || field.image_quality_milli > 1_000
        || field.spatial_novelty_milli > 1_000
        || (field.invasion_axis_x_milli == 0 && field.invasion_axis_y_milli == 0)
        || field.invasion_axis_x_milli.unsigned_abs() > MAX_COORDINATE_MILLI as u64
        || field.invasion_axis_y_milli.unsigned_abs() > MAX_COORDINATE_MILLI as u64
        || field.tracks.len() > MAX_TRACKS_PER_FIELD
    {
        return Err(invalid_field(format!(
            "field {} has invalid identity, axis, scores, or size",
            field.field_id
        )));
    }
    field
        .artifact
        .validate()
        .map_err(|error| invalid_field(error.to_string()))?;
    let track_ids = field
        .tracks
        .iter()
        .map(|track| track.track_id.as_str())
        .collect::<Vec<_>>();
    if !track_ids.windows(2).all(|pair| pair[0] < pair[1]) {
        return Err(invalid_field(format!(
            "field {} tracks must be uniquely sorted",
            field.field_id
        )));
    }
    let mut total_frames = 0usize;
    for track in &field.tracks {
        if track.track_id.trim().is_empty()
            || track.frames.len() < 2
            || track.frames.len() > MAX_FRAMES_PER_TRACK
        {
            return Err(invalid_field(format!(
                "track {} has invalid identity or frame count",
                track.track_id
            )));
        }
        total_frames = total_frames.saturating_add(track.frames.len());
        for (index, frame) in track.frames.iter().enumerate() {
            if frame.time_millis > MAX_TIME_MILLIS
                || frame.x_micrometre_milli.unsigned_abs() > MAX_COORDINATE_MILLI as u64
                || frame.y_micrometre_milli.unsigned_abs() > MAX_COORDINATE_MILLI as u64
                || frame.area_micrometre_squared_milli == 0
                || frame.area_micrometre_squared_milli > MAX_FEATURE_MILLI as u64
                || frame.elongation_permille < 1_000
                || frame.elongation_permille as i64 > MAX_FEATURE_MILLI
                || (index > 0 && field_time(frame) <= field_time(&track.frames[index - 1]))
            {
                return Err(invalid_field(format!(
                    "track {} contains invalid or nonmonotonic frame data",
                    track.track_id
                )));
            }
        }
    }
    if total_frames > MAX_TRACKS_PER_FIELD.saturating_mul(MAX_FRAMES_PER_TRACK) {
        return Err(invalid_field(format!(
            "field {} exceeds the bounded frame budget",
            field.field_id
        )));
    }
    Ok(())
}

fn field_time(frame: &CellTrackFrame) -> u64 {
    frame.time_millis
}

fn integer_sqrt(value: u128) -> u128 {
    if value < 2 {
        return value;
    }
    let mut x = value;
    let mut y = (x + 1) / 2;
    while y < x {
        x = y;
        y = (x + value / x) / 2;
    }
    x
}

fn median_i64(values: &mut [i64]) -> i64 {
    if values.is_empty() {
        return 0;
    }
    values.sort_unstable();
    let middle = values.len() / 2;
    if values.len() % 2 == 0 {
        ((values[middle - 1] as i128 + values[middle] as i128) / 2) as i64
    } else {
        values[middle]
    }
}

fn rounded_ratio(numerator: u128, denominator: u128) -> u128 {
    if denominator == 0 {
        return 0;
    }
    numerator.saturating_add(denominator / 2) / denominator
}

fn track_features(
    field: &MicroscopyFieldInput,
    track: &TrackedGliomaCell,
) -> Result<Vec<i64>, MicroscopyMorphodynamicError> {
    let first = &track.frames[0];
    let last = track.frames.last().expect("validated non-empty track");
    let elapsed = last.time_millis - first.time_millis;
    let mut path_milli = 0u128;
    let mut speeds = Vec::with_capacity(track.frames.len().saturating_sub(1));
    for pair in track.frames.windows(2) {
        let dx = pair[1].x_micrometre_milli as i128 - pair[0].x_micrometre_milli as i128;
        let dy = pair[1].y_micrometre_milli as i128 - pair[0].y_micrometre_milli as i128;
        let squared = dx
            .unsigned_abs()
            .saturating_mul(dx.unsigned_abs())
            .saturating_add(dy.unsigned_abs().saturating_mul(dy.unsigned_abs()));
        let distance = integer_sqrt(squared);
        path_milli = path_milli.saturating_add(distance);
        let duration = (pair[1].time_millis - pair[0].time_millis) as u128;
        speeds.push(rounded_ratio(distance.saturating_mul(3_600_000), duration));
    }
    let net_x = last.x_micrometre_milli as i128 - first.x_micrometre_milli as i128;
    let net_y = last.y_micrometre_milli as i128 - first.y_micrometre_milli as i128;
    let net_squared = net_x
        .unsigned_abs()
        .saturating_mul(net_x.unsigned_abs())
        .saturating_add(net_y.unsigned_abs().saturating_mul(net_y.unsigned_abs()));
    let net = integer_sqrt(net_squared);
    let persistence = rounded_ratio(net.saturating_mul(1_000), path_milli).min(1_000) as i64;
    let axis_x = field.invasion_axis_x_milli as i128;
    let axis_y = field.invasion_axis_y_milli as i128;
    let axis_squared = axis_x
        .unsigned_abs()
        .saturating_mul(axis_x.unsigned_abs())
        .saturating_add(axis_y.unsigned_abs().saturating_mul(axis_y.unsigned_abs()));
    let axis_norm = integer_sqrt(axis_squared);
    let alignment_denominator = axis_norm.saturating_mul(net);
    let alignment_numerator = (net_x * axis_x + net_y * axis_y) * 1_000;
    let alignment = if alignment_denominator == 0 {
        0
    } else {
        (alignment_numerator / alignment_denominator as i128).clamp(-1_000, 1_000) as i64
    };
    let speed_values = speeds
        .iter()
        .map(|value| (*value).min(i64::MAX as u128) as i64)
        .collect::<Vec<_>>();
    let mean_speed = (speed_values
        .iter()
        .map(|value| *value as i128)
        .sum::<i128>()
        / speed_values.len() as i128)
        .max(0) as u128;
    let mean_square = speed_values
        .iter()
        .map(|value| (*value as u128).saturating_mul(*value as u128))
        .sum::<u128>()
        / speed_values.len() as u128;
    let variance = mean_square.saturating_sub(mean_speed.saturating_mul(mean_speed));
    let speed_cv = if mean_speed == 0 {
        0
    } else {
        rounded_ratio(integer_sqrt(variance).saturating_mul(1_000), mean_speed).min(10_000) as i64
    };
    let speed_per_hour_milli = rounded_ratio(path_milli.saturating_mul(3_600_000), elapsed as u128);
    if speed_per_hour_milli > MAX_FEATURE_MILLI as u128 {
        return Err(invalid_field(format!(
            "track {} speed exceeds supported fixed-point range",
            track.track_id
        )));
    }
    let elongations = track
        .frames
        .iter()
        .map(|frame| frame.elongation_permille as i64)
        .collect::<Vec<_>>();
    let mean_elongation =
        elongations.iter().map(|value| *value as i128).sum::<i128>() / elongations.len() as i128;
    let elongation_median = median_i64(&mut elongations.clone());
    let mut elongation_deviations = elongations
        .iter()
        .map(|value| (*value - elongation_median).abs())
        .collect::<Vec<_>>();
    let elongation_mad = median_i64(&mut elongation_deviations);
    let branch_milli = (track
        .frames
        .iter()
        .map(|frame| frame.branch_count as u128)
        .sum::<u128>()
        .saturating_mul(1_000)
        / track.frames.len() as u128)
        .min(MAX_FEATURE_MILLI as u128) as i64;
    Ok(vec![
        branch_milli,
        persistence,
        elongation_mad,
        alignment,
        mean_elongation as i64,
        speed_cv,
        speed_per_hour_milli as i64,
    ])
}

fn derive_field(
    field: &MicroscopyFieldInput,
) -> Result<Option<DerivedField>, MicroscopyMorphodynamicError> {
    validate_field(field)?;
    if field.tracks.is_empty() {
        return Ok(None);
    }
    let mut tracks = vec![Vec::<i64>::new(); MORPHODYNAMIC_FEATURE_ORDER.len()];
    for track in &field.tracks {
        for (index, value) in track_features(field, track)?.into_iter().enumerate() {
            tracks[index].push(value);
        }
    }
    let features = tracks.iter_mut().map(|values| median_i64(values)).collect();
    Ok(Some(DerivedField {
        unit_id: field.independent_unit_id.clone(),
        features,
    }))
}

fn feature_values(values: &[i64]) -> Vec<FeatureValue> {
    MORPHODYNAMIC_FEATURE_ORDER
        .iter()
        .zip(values)
        .map(|(feature_id, value_milli)| FeatureValue {
            feature_id: (*feature_id).into(),
            value_milli: *value_milli,
        })
        .collect()
}

fn state_median(vectors: &[Vec<i64>]) -> Vec<i64> {
    (0..MORPHODYNAMIC_FEATURE_ORDER.len())
        .map(|index| {
            let mut values = vectors
                .iter()
                .map(|vector| vector[index])
                .collect::<Vec<_>>();
            median_i64(&mut values)
        })
        .collect()
}

fn prototype_model(
    samples: &[(String, String, Vec<i64>)],
    state_order: &[String],
    min_feature_scale_milli: u64,
) -> (Vec<Vec<i64>>, Vec<u64>, Vec<u16>) {
    let mut unit_state: BTreeMap<(String, String), Vec<Vec<i64>>> = BTreeMap::new();
    for (state, unit, vector) in samples {
        unit_state
            .entry((state.clone(), unit.clone()))
            .or_default()
            .push(vector.clone());
    }
    let unit_vectors = unit_state
        .iter()
        .map(|((state, unit), vectors)| (state.clone(), unit.clone(), state_median(vectors)))
        .collect::<Vec<_>>();
    let prototypes = state_order
        .iter()
        .map(|state| {
            let vectors = unit_vectors
                .iter()
                .filter(|(candidate, _, _)| candidate == state)
                .map(|(_, _, vector)| vector.clone())
                .collect::<Vec<_>>();
            state_median(&vectors)
        })
        .collect::<Vec<_>>();
    let scales = (0..MORPHODYNAMIC_FEATURE_ORDER.len())
        .map(|feature_index| {
            let mut deviations = unit_vectors
                .iter()
                .map(|(state, _, vector)| {
                    (vector[feature_index]
                        - prototypes[state_order.binary_search(state).unwrap()][feature_index])
                        .abs()
                })
                .collect::<Vec<_>>();
            let mad = median_i64(&mut deviations);
            ((mad as u128).saturating_mul(1_483).saturating_add(500) / 1_000)
                .max(min_feature_scale_milli as u128)
                .min(u64::MAX as u128) as u64
        })
        .collect();
    let counts = state_order
        .iter()
        .map(|state| {
            unit_vectors
                .iter()
                .filter(|(candidate, _, _)| candidate == state)
                .count()
                .min(u16::MAX as usize) as u16
        })
        .collect();
    (prototypes, scales, counts)
}

fn classify(
    vector: &[i64],
    prototypes: &[Vec<i64>],
    scales: &[u64],
    unit_counts: &[u16],
) -> (Vec<u16>, u64) {
    let distances = prototypes
        .iter()
        .map(|prototype| {
            vector
                .iter()
                .zip(prototype)
                .zip(scales)
                .map(|((value, center), scale)| {
                    (value.abs_diff(*center) as u128).saturating_mul(1_000)
                        / (*scale).max(1) as u128
                })
                .sum::<u128>()
        })
        .collect::<Vec<_>>();
    let nearest = distances
        .iter()
        .copied()
        .min()
        .unwrap_or(u128::MAX)
        .min(u64::MAX as u128) as u64;
    let weights = distances
        .iter()
        .zip(unit_counts)
        .map(|(distance, units)| {
            (*units as u128).saturating_mul(1_000_000_000_000u128)
                / (1_000u128.saturating_add(*distance))
        })
        .collect::<Vec<_>>();
    let total = weights.iter().sum::<u128>();
    if total == 0 {
        return (vec![0; prototypes.len()], nearest);
    }
    let mut probabilities = weights
        .iter()
        .map(|weight| (weight.saturating_mul(1_000) / total) as u16)
        .collect::<Vec<_>>();
    let mut remaining = 1_000u16.saturating_sub(probabilities.iter().copied().sum::<u16>());
    let remainders = weights
        .iter()
        .map(|weight| weight.saturating_mul(1_000) % total)
        .collect::<Vec<_>>();
    let mut index_order = (0..weights.len()).collect::<Vec<_>>();
    index_order.sort_by_key(|index| (std::cmp::Reverse(remainders[*index]), *index));
    for index in index_order {
        if remaining == 0 {
            break;
        }
        probabilities[index] = probabilities[index].saturating_add(1);
        remaining -= 1;
    }
    (probabilities, nearest)
}

fn argmax(values: &[u16]) -> usize {
    values
        .iter()
        .enumerate()
        .max_by_key(|(index, value)| (**value, std::cmp::Reverse(*index)))
        .map(|(index, _)| index)
        .unwrap_or(0)
}

fn normalize_column(counts: &[u128], smoothing: u16) -> Vec<u16> {
    let mut weights = counts
        .iter()
        .map(|count| count.saturating_add(smoothing as u128))
        .collect::<Vec<_>>();
    let mut total = weights.iter().sum::<u128>();
    if total == 0 {
        weights.fill(1);
        total = weights.iter().sum::<u128>();
    }
    let mut probabilities = weights
        .iter()
        .map(|weight| (weight.saturating_mul(1_000) / total) as u16)
        .collect::<Vec<_>>();
    let mut remaining = 1_000u16.saturating_sub(probabilities.iter().copied().sum::<u16>());
    let remainders = weights
        .iter()
        .map(|weight| weight.saturating_mul(1_000) % total)
        .collect::<Vec<_>>();
    let mut order = (0..weights.len()).collect::<Vec<_>>();
    order.sort_by_key(|index| (std::cmp::Reverse(remainders[*index]), *index));
    for index in order {
        if remaining == 0 {
            break;
        }
        probabilities[index] = probabilities[index].saturating_add(1);
        remaining -= 1;
    }
    probabilities
}

impl MicroscopyMorphodynamicAnalysis {
    pub fn validate(&self) -> Result<(), MicroscopyMorphodynamicError> {
        if self.feature_id != FEATURE_ID
            || self.output_schema != OUTPUT_SCHEMA
            || self.study_id.trim().is_empty()
            || self.model_system != self.material.model_system()
            || !canonical(&self.state_order)
            || self.state_order.len() < 2
            || self
                .feature_order
                .iter()
                .map(String::as_str)
                .collect::<Vec<_>>()
                != MORPHODYNAMIC_FEATURE_ORDER
            || self.prototype_features.len() != self.state_order.len()
            || self
                .prototype_features
                .iter()
                .any(|row| row.len() != self.feature_order.len())
            || self.robust_feature_scales_milli.len() != self.feature_order.len()
            || self.robust_feature_scales_milli.contains(&0)
            || self.min_posterior_milli > 1_000
            || self.min_posterior_margin_milli > 1_000
            || self.state_unit_counts.len() != self.state_order.len()
            || self.validation.len() != self.state_order.len()
            || self.outcome_model.len() != self.state_order.len()
            || self.outcome_model.iter().any(|outcome| {
                outcome.outcome_id.trim().is_empty()
                    || outcome.likelihood_by_state_milli.len() != self.state_order.len()
                    || outcome
                        .likelihood_by_state_milli
                        .iter()
                        .any(|value| *value > 1_000)
            })
            || (0..self.state_order.len()).any(|state_index| {
                self.outcome_model
                    .iter()
                    .map(|outcome| outcome.likelihood_by_state_milli[state_index] as u32)
                    .sum::<u32>()
                    != 1_000
            })
            || self
                .outcome_model
                .iter()
                .map(|outcome| outcome.outcome_id.clone())
                .collect::<Vec<_>>()
                != self.state_order
            || self
                .validation
                .iter()
                .map(|entry| entry.state_id.clone())
                .collect::<Vec<_>>()
                != self.state_order
            || self
                .validation
                .iter()
                .zip(&self.state_unit_counts)
                .any(|(entry, count)| {
                    entry.independent_unit_count != *count || entry.recall_milli > 1_000
                })
            || self.balanced_accuracy_milli > 1_000
            || !canonical(&self.field_order)
            || self
                .fields
                .iter()
                .map(|field| field.field_id.clone())
                .collect::<Vec<_>>()
                != self.field_order
            || self.fields.iter().any(|field| {
                field.material != self.material
                    || field
                        .state_posterior
                        .iter()
                        .any(|value| value.probability_milli > 1_000)
                    || (!field.state_posterior.is_empty()
                        && field
                            .state_posterior
                            .iter()
                            .map(|value| value.probability_milli as u32)
                            .sum::<u32>()
                            != 1_000)
                    || (!field.state_posterior.is_empty()
                        && field
                            .state_posterior
                            .iter()
                            .map(|value| value.state_id.clone())
                            .collect::<Vec<_>>()
                            != self.state_order)
                    || (!field.morphodynamic_features.is_empty()
                        && field
                            .morphodynamic_features
                            .iter()
                            .map(|feature| feature.feature_id.clone())
                            .collect::<Vec<_>>()
                            != self.feature_order)
                    || field.source_artifact.validate().is_err()
                    || field.analysis_artifact.validate().is_err()
            })
            || !canonical(&self.negative_evidence)
            || !canonical(&self.uncertainty)
        {
            return Err(MicroscopyMorphodynamicError::InvalidOutput(
                "model identity, canonical ordering, posterior, calibration, or field contract is inconsistent".into(),
            ));
        }
        let expected = ContentHash::of_value(&digest_input(self))
            .map_err(|error| MicroscopyMorphodynamicError::Digest(error.to_string()))?;
        if expected != self.digest {
            return Err(MicroscopyMorphodynamicError::Digest(
                "analysis digest does not match canonical output".into(),
            ));
        }
        Ok(())
    }
}

fn validate_request(
    request: &MicroscopyMorphodynamicRequest,
    references: &[LabeledMorphodynamicField],
    targets: &[MicroscopyFieldInput],
) -> Result<(), MicroscopyMorphodynamicError> {
    if request.study_id.trim().is_empty()
        || request.min_independent_units_per_state < 2
        || request.min_tracks_per_field == 0
        || request.min_image_quality_milli > 1_000
        || request.min_balanced_accuracy_milli > 1_000
        || request.max_multiclass_brier_milli > 2_000
        || request.min_feature_scale_milli == 0
        || request.min_feature_scale_milli > MAX_FEATURE_MILLI as u64
        || request.max_out_of_domain_distance_milli == 0
        || request.max_out_of_domain_distance_milli > MAX_DISTANCE_MILLI
        || request.min_posterior_milli > 1_000
        || request.min_posterior_margin_milli > 1_000
        || request.confusion_smoothing_milli > 1_000
        || references.is_empty()
        || references.len() > MAX_REFERENCE_FIELDS
        || targets.len() > MAX_TARGET_FIELDS
    {
        return Err(MicroscopyMorphodynamicError::InvalidRequest(
            "request thresholds, study identity, or bounded field counts are invalid".into(),
        ));
    }
    request
        .analysis_artifact
        .validate()
        .map_err(|error| MicroscopyMorphodynamicError::InvalidRequest(error.to_string()))?;
    let reference_ids = references
        .iter()
        .map(|sample| sample.field.field_id.as_str())
        .collect::<Vec<_>>();
    let target_ids = targets
        .iter()
        .map(|field| field.field_id.as_str())
        .collect::<Vec<_>>();
    if !reference_ids.windows(2).all(|pair| pair[0] < pair[1])
        || !target_ids.windows(2).all(|pair| pair[0] < pair[1])
    {
        return Err(MicroscopyMorphodynamicError::InvalidRequest(
            "reference and target fields must be uniquely sorted by field_id".into(),
        ));
    }
    let mut states = BTreeSet::new();
    let mut independent_units = BTreeSet::new();
    let mut unit_labels = BTreeMap::<String, String>::new();
    for labeled in references {
        if labeled.state_id.trim().is_empty() || labeled.state_id.len() > 128 {
            return Err(MicroscopyMorphodynamicError::InvalidRequest(
                "reference phenotype labels must be non-empty and bounded".into(),
            ));
        }
        if labeled.field.material != request.material {
            return Err(invalid_field(format!(
                "field {} uses a different material than the request",
                labeled.field.field_id
            )));
        }
        validate_field(&labeled.field)?;
        if labeled.field.tracks.len() < request.min_tracks_per_field as usize {
            return Err(invalid_field(format!(
                "reference field {} has fewer than the required tracks",
                labeled.field.field_id
            )));
        }
        states.insert(labeled.state_id.clone());
        independent_units.insert(labeled.field.independent_unit_id.clone());
        if let Some(previous_state) = unit_labels.insert(
            labeled.field.independent_unit_id.clone(),
            labeled.state_id.clone(),
        ) {
            if previous_state != labeled.state_id {
                return Err(MicroscopyMorphodynamicError::InvalidRequest(format!(
                    "independent unit {} has conflicting phenotype labels {} and {}",
                    labeled.field.independent_unit_id, previous_state, labeled.state_id
                )));
            }
        }
    }
    if states.len() < 2
        || states.len() > MAX_STATES
        || independent_units.len() > MAX_INDEPENDENT_UNITS
    {
        return Err(MicroscopyMorphodynamicError::InvalidRequest(
            "reference labels require 2..=32 states and a bounded number of independent units"
                .into(),
        ));
    }
    for field in targets {
        if field.material != request.material {
            return Err(invalid_field(format!(
                "target field {} uses a different material than the request",
                field.field_id
            )));
        }
        validate_field(field)?;
    }
    Ok(())
}

/// Derive state posteriors from segmented local tracks and calibrate them by holding out complete
/// biological units. Cells, frames, and fields never increase the independent-unit count.
pub fn analyze_glioma_microscopy_morphodynamics(
    request: &MicroscopyMorphodynamicRequest,
    references: &[LabeledMorphodynamicField],
    targets: &[MicroscopyFieldInput],
) -> Result<MicroscopyMorphodynamicAnalysis, MicroscopyMorphodynamicError> {
    validate_request(request, references, targets)?;
    let state_order = references
        .iter()
        .map(|sample| sample.state_id.clone())
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect::<Vec<_>>();
    let mut samples = Vec::with_capacity(references.len());
    for labeled in references {
        let derived = derive_field(&labeled.field)?.ok_or_else(|| {
            invalid_field(format!(
                "reference field {} contains no tracks",
                labeled.field.field_id
            ))
        })?;
        samples.push((labeled.state_id.clone(), derived.unit_id, derived.features));
    }
    let mut state_units: BTreeMap<String, BTreeSet<String>> = state_order
        .iter()
        .map(|state| (state.clone(), BTreeSet::new()))
        .collect();
    for (state, unit, _) in &samples {
        state_units
            .get_mut(state)
            .expect("validated state")
            .insert(unit.clone());
    }
    let (prototype_vectors, scales, unit_counts) =
        prototype_model(&samples, &state_order, request.min_feature_scale_milli);

    let all_units = samples
        .iter()
        .map(|(_, unit, _)| unit.clone())
        .collect::<BTreeSet<_>>();
    let mut unit_state_probabilities: BTreeMap<(String, String), Vec<Vec<u16>>> = BTreeMap::new();
    let mut fold_count = 0usize;
    for held_out_unit in &all_units {
        let training = samples
            .iter()
            .filter(|(_, unit, _)| unit != held_out_unit)
            .cloned()
            .collect::<Vec<_>>();
        if state_order
            .iter()
            .any(|state| !training.iter().any(|(label, _, _)| label == state))
        {
            continue;
        }
        let (fold_prototypes, fold_scales, fold_counts) =
            prototype_model(&training, &state_order, request.min_feature_scale_milli);
        fold_count += 1;
        for labeled in references
            .iter()
            .filter(|sample| sample.field.independent_unit_id == *held_out_unit)
        {
            let derived = derive_field(&labeled.field)?.expect("reference track validation");
            let (posterior, _) = classify(
                &derived.features,
                &fold_prototypes,
                &fold_scales,
                &fold_counts,
            );
            unit_state_probabilities
                .entry((labeled.state_id.clone(), held_out_unit.clone()))
                .or_default()
                .push(posterior);
        }
    }

    let mut state_recall = BTreeMap::new();
    let mut brier_sum = 0u128;
    let mut brier_count = 0u128;
    let mut confusion = vec![vec![0u128; state_order.len()]; state_order.len()];
    let mut heldout_by_state = BTreeMap::<String, u16>::new();
    for state in &state_order {
        let heldout = unit_state_probabilities
            .iter()
            .filter(|((label, _), _)| label == state)
            .collect::<Vec<_>>();
        let correct = heldout
            .iter()
            .filter(|(_, posteriors)| {
                let mean = average_posteriors(posteriors);
                argmax(&mean) == state_order.binary_search(state).unwrap()
            })
            .count();
        let recall = if heldout.is_empty() {
            0
        } else {
            (correct * 1_000 / heldout.len()) as u16
        };
        state_recall.insert(state.clone(), recall);
        heldout_by_state.insert(state.clone(), heldout.len().min(u16::MAX as usize) as u16);
    }
    for ((true_state, _unit), posteriors) in &unit_state_probabilities {
        let probabilities = average_posteriors(posteriors);
        let actual = state_order.binary_search(true_state).unwrap();
        for (predicted, probability) in probabilities.iter().enumerate() {
            confusion[predicted][actual] =
                confusion[predicted][actual].saturating_add(*probability as u128);
            let target = if predicted == actual { 1_000i128 } else { 0 };
            let delta = *probability as i128 - target;
            brier_sum = brier_sum.saturating_add((delta * delta) as u128);
        }
        brier_count += 1;
    }
    let participating_states = state_recall
        .iter()
        .filter(|(state, _)| heldout_by_state.get(*state).copied().unwrap_or(0) > 0)
        .count();
    let balanced_accuracy = if participating_states == 0 {
        0
    } else {
        (state_recall
            .iter()
            .filter(|(state, _)| heldout_by_state.get(*state).copied().unwrap_or(0) > 0)
            .map(|(_, recall)| *recall as u32)
            .sum::<u32>()
            / participating_states as u32) as u16
    };
    let brier = if brier_count == 0 {
        2_000
    } else {
        ((brier_sum.saturating_mul(1_000) / brier_count / 1_000_000).min(2_000)) as u16
    };
    let outcome_model = (0..state_order.len())
        .map(|predicted_index| MicroscopyOutcomeLikelihood {
            outcome_id: state_order[predicted_index].clone(),
            likelihood_by_state_milli: (0..state_order.len())
                .map(|true_index| {
                    normalize_column(
                        &confusion
                            .iter()
                            .map(|row| row[true_index])
                            .collect::<Vec<_>>(),
                        request.confusion_smoothing_milli,
                    )[predicted_index]
                })
                .collect(),
        })
        .collect::<Vec<_>>();
    let validation = state_order
        .iter()
        .map(|state| StateValidationSummary {
            state_id: state.clone(),
            independent_unit_count: state_units[state].len().min(u16::MAX as usize) as u16,
            held_out_unit_count: heldout_by_state[state],
            recall_milli: state_recall[state],
        })
        .collect::<Vec<_>>();
    let validation_support = state_order.iter().all(|state| {
        state_units[state].len() >= request.min_independent_units_per_state as usize
            && heldout_by_state[state] >= request.min_independent_units_per_state
    }) && fold_count >= request.min_independent_units_per_state as usize;
    let disposition = if !validation_support {
        MorphodynamicModelDisposition::InsufficientValidation
    } else if balanced_accuracy >= request.min_balanced_accuracy_milli
        && brier <= request.max_multiclass_brier_milli
    {
        MorphodynamicModelDisposition::Qualified
    } else {
        MorphodynamicModelDisposition::Unqualified
    };
    let mut negative_evidence = BTreeSet::new();
    if !validation_support {
        negative_evidence.insert(
            "independent-unit-held-out-validation-support-below-requested-floor".to_string(),
        );
    }
    if validation_support && balanced_accuracy < request.min_balanced_accuracy_milli {
        negative_evidence.insert("held-out-balanced-accuracy-below-requested-gate".to_string());
    }
    if validation_support && brier > request.max_multiclass_brier_milli {
        negative_evidence.insert("held-out-multiclass-brier-above-requested-gate".to_string());
    }
    let mut fields = Vec::with_capacity(targets.len());
    for target in targets {
        let derived = derive_field(target)?;
        let track_count = target.tracks.len().min(u16::MAX as usize) as u16;
        let mut uncertainty = BTreeSet::new();
        let (features, posterior, distance, field_disposition) = match derived {
            None => {
                uncertainty.insert("no-segmented-tracks-available".to_string());
                (
                    Vec::new(),
                    Vec::new(),
                    0,
                    MorphodynamicFieldDisposition::InsufficientTracks,
                )
            }
            Some(derived) => {
                let (posterior_raw, distance) =
                    classify(&derived.features, &prototype_vectors, &scales, &unit_counts);
                let top_probability = posterior_raw.iter().copied().max().unwrap_or(0);
                let top_index = argmax(&posterior_raw);
                let runner_up_probability = posterior_raw
                    .iter()
                    .copied()
                    .enumerate()
                    .filter(|(index, _)| *index != top_index)
                    .map(|(_, probability)| probability)
                    .max()
                    .unwrap_or(0);
                let posterior_margin = top_probability.saturating_sub(runner_up_probability);
                let posterior = state_order
                    .iter()
                    .zip(posterior_raw)
                    .map(|(state_id, probability_milli)| MicroscopyStateProbability {
                        state_id: state_id.clone(),
                        probability_milli,
                    })
                    .collect::<Vec<_>>();
                let disposition = if target.tracks.len() < request.min_tracks_per_field as usize {
                    uncertainty.insert("track-count-below-requested-minimum".to_string());
                    MorphodynamicFieldDisposition::InsufficientTracks
                } else if target.image_quality_milli < request.min_image_quality_milli {
                    uncertainty.insert("image-quality-below-requested-minimum".to_string());
                    MorphodynamicFieldDisposition::LowImageQuality
                } else if distance > request.max_out_of_domain_distance_milli {
                    uncertainty
                        .insert("morphodynamic-profile-outside-reference-domain".to_string());
                    MorphodynamicFieldDisposition::OutOfDomain
                } else if top_probability < request.min_posterior_milli
                    || posterior_margin < request.min_posterior_margin_milli
                {
                    uncertainty.insert(
                        "posterior-confidence-or-margin-below-requested-minimum".to_string(),
                    );
                    MorphodynamicFieldDisposition::AmbiguousPosterior
                } else {
                    MorphodynamicFieldDisposition::Classified
                };
                (
                    feature_values(&derived.features),
                    posterior,
                    distance,
                    disposition,
                )
            }
        };
        if disposition != MorphodynamicModelDisposition::Qualified {
            uncertainty
                .insert("reference-model-did-not-pass-all-requested-held-out-gates".to_string());
        }
        fields.push(MorphodynamicFieldEstimate {
            field_id: target.field_id.clone(),
            region_id: target.region_id.clone(),
            independent_unit_id: target.independent_unit_id.clone(),
            biological_stratum: target.biological_stratum.clone(),
            material: target.material,
            image_quality_milli: target.image_quality_milli,
            spatial_novelty_milli: target.spatial_novelty_milli,
            track_count,
            morphodynamic_features: features,
            state_posterior: if disposition == MorphodynamicModelDisposition::Qualified
                && matches!(
                    field_disposition,
                    MorphodynamicFieldDisposition::Classified
                        | MorphodynamicFieldDisposition::AmbiguousPosterior
                ) {
                posterior
            } else {
                Vec::new()
            },
            nearest_reference_distance_milli: distance,
            disposition: field_disposition,
            uncertainty: uncertainty.into_iter().collect(),
            source_artifact: target.artifact.clone(),
            analysis_artifact: request.analysis_artifact.clone(),
        });
    }
    let mut uncertainty = BTreeSet::from([
        "motion-features-are-derived-from-two-dimensional-segmented-tracks-and-do-not-establish-causal-state".to_string(),
        "state-labels-are-provided-by-the-researcher-or-independent-assay-and-are-not-generated-from-imaging".to_string(),
    ]);
    if !validation_support {
        uncertainty.insert("validation-is-biological-unit-held-out-but-does-not-yet-meet-requested-independent-unit-count".to_string());
    }
    let mut output = MicroscopyMorphodynamicAnalysis {
        feature_id: FEATURE_ID.into(),
        output_schema: OUTPUT_SCHEMA.into(),
        study_id: request.study_id.clone(),
        material: request.material,
        model_system: request.material.model_system(),
        state_order,
        feature_order: MORPHODYNAMIC_FEATURE_ORDER
            .iter()
            .map(|feature| (*feature).to_string())
            .collect(),
        prototype_features: prototype_vectors
            .iter()
            .map(|vector| feature_values(vector))
            .collect(),
        robust_feature_scales_milli: scales,
        state_unit_counts: unit_counts,
        min_posterior_milli: request.min_posterior_milli,
        min_posterior_margin_milli: request.min_posterior_margin_milli,
        validation,
        outcome_model,
        balanced_accuracy_milli: balanced_accuracy,
        multiclass_brier_milli: brier,
        validation_fold_count: fold_count.min(u16::MAX as usize) as u16,
        field_order: fields.iter().map(|field| field.field_id.clone()).collect(),
        fields,
        disposition,
        negative_evidence: negative_evidence.into_iter().collect(),
        uncertainty: uncertainty.into_iter().collect(),
        digest: ContentHash::of_bytes(b"pending"),
    };
    output.digest = ContentHash::of_value(&digest_input(&output))
        .map_err(|error| MicroscopyMorphodynamicError::Digest(error.to_string()))?;
    output.validate()?;
    Ok(output)
}

fn average_posteriors(posteriors: &[Vec<u16>]) -> Vec<u16> {
    if posteriors.is_empty() {
        return Vec::new();
    }
    let mut sums = vec![0u128; posteriors[0].len()];
    for posterior in posteriors {
        for (sum, value) in sums.iter_mut().zip(posterior) {
            *sum = sum.saturating_add(*value as u128);
        }
    }
    let count = posteriors.len() as u128;
    let weights = sums.iter().map(|sum| sum / count).collect::<Vec<_>>();
    let total = weights.iter().sum::<u128>();
    if total == 0 {
        return vec![0; weights.len()];
    }
    let mut output = weights
        .iter()
        .map(|weight| (weight.saturating_mul(1_000) / total) as u16)
        .collect::<Vec<_>>();
    let mut remaining = 1_000u16.saturating_sub(output.iter().copied().sum::<u16>());
    let remainders = weights
        .iter()
        .map(|weight| weight.saturating_mul(1_000) % total)
        .collect::<Vec<_>>();
    let mut order = (0..weights.len()).collect::<Vec<_>>();
    order.sort_by_key(|index| (std::cmp::Reverse(remainders[*index]), *index));
    for index in order {
        if remaining == 0 {
            break;
        }
        output[index] = output[index].saturating_add(1);
        remaining -= 1;
    }
    output
}

