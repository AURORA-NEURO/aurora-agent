    #[test]
    fn computes_information_gain_and_executes_only_a_coverage_frontier_capture() {
        let mut req = request(vec![
            candidate("core-candidate", "field-core", "core", 500),
            candidate("front-candidate", "field-front", "invasion-front", 300),
        ]);
        let estimates = scientific_estimate(&req.candidates[1]);
        assert!(
            estimates.0 > 0,
            "discriminating outcomes should reduce posterior entropy"
        );
        assert!(estimates.1 > 0);

        let mut executor = DryRunInstrumentExecutor {
            interlocks: interlocks(),
            emergency_stop_called: false,
        };
        let round = execute_glioma_adaptive_microscopy_round(&req, &mut executor).unwrap();
        assert_eq!(round.disposition, AdaptiveMicroscopyDisposition::Simulated);
        assert_eq!(
            round.selected_candidate_id.as_deref(),
            Some("front-candidate")
        );
        assert_eq!(round.selected_field_id.as_deref(), Some("field-front"));
        assert_eq!(
            round.execution.as_ref().unwrap().completed_order,
            vec!["capture-field-front"]
        );
        assert_eq!(round.estimated_dose_milli, 33);
        assert_eq!(
            round.spent_dose_milli, 0,
            "a dry run must not consume the specimen's light budget"
        );
        assert!(round
            .negative_evidence
            .iter()
            .any(|item| item.contains("not-biological-evidence")));
        round.validate().unwrap();

        req.candidates.reverse();
        let mut executor = DryRunInstrumentExecutor {
            interlocks: interlocks(),
            emergency_stop_called: false,
        };
        let replay = execute_glioma_adaptive_microscopy_round(&req, &mut executor).unwrap();
        assert_eq!(
            round, replay,
            "input order must not alter the decision or digest"
        );
    }

