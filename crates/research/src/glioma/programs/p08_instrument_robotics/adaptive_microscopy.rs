//! Dose-aware, uncertainty-driven adaptive microscopy for preclinical glioma models.
//!
//! Each call selects and executes one field-of-view capture, then returns its actual local
//! instrument result so an institution-owned image-analysis pipeline can refresh its state and
//! request the next round. Required biological strata receive a coverage floor; remaining fields
//! are ranked by expected information, uncertainty, quality, spatial novelty, and conservative
//! calibrated light dose. Physical execution reuses P08 authorization and interlock gates. This is
//! not an image classifier and a capture or dry run is never treated as biological evidence.

