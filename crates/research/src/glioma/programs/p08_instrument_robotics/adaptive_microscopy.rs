/// One actual or simulated acquisition decision; captured image data remains at the institution.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AdaptiveMicroscopyRound {
    pub feature_id: String,
    pub output_schema: String,
    pub objective: String,
    pub instrument_id: String,
    pub candidate_order: Vec<String>,
    pub decisions: Vec<MicroscopyCandidateDecision>,
    pub selected_candidate_id: Option<String>,
    pub selected_field_id: Option<String>,
    pub selected_stratum: Option<String>,
    pub estimated_dose_milli: u64,
    pub spent_dose_milli: u64,
    pub remaining_dose_milli: u64,
    pub execution: Option<InstrumentExecutionRun>,
    pub simulation_only: bool,
    pub disposition: AdaptiveMicroscopyDisposition,
    pub stop_reason: AdaptiveMicroscopyStopReason,
    pub next_round_guidance: String,
    pub negative_evidence: Vec<String>,
    pub uncertainty: Vec<String>,
    pub digest: ContentHash,
}

#[derive(Debug, Error, PartialEq, Eq)]
pub enum AdaptiveMicroscopyError {
    #[error("adaptive glioma microscopy request is invalid: {0}")]
    InvalidRequest(String),
    #[error("guarded instrument execution failed: {0}")]
    Execution(#[from] InstrumentExecutionError),
    #[error("adaptive microscopy output is invalid: {0}")]
    InvalidOutput(String),
    #[error("adaptive microscopy digest failed: {0}")]
    Digest(String),
}

fn canonical(values: &[String]) -> bool {
    values.windows(2).all(|pair| pair[0] < pair[1])
}

fn digest_input(round: &AdaptiveMicroscopyRound) -> serde_json::Value {
    serde_json::json!({
        "feature_id": round.feature_id, "output_schema": round.output_schema,
        "objective": round.objective, "instrument_id": round.instrument_id,
        "candidate_order": round.candidate_order, "decisions": round.decisions,
        "selected_candidate_id": round.selected_candidate_id,
        "selected_field_id": round.selected_field_id, "selected_stratum": round.selected_stratum,
        "estimated_dose_milli": round.estimated_dose_milli,
        "spent_dose_milli": round.spent_dose_milli,
        "remaining_dose_milli": round.remaining_dose_milli, "execution": round.execution,
        "simulation_only": round.simulation_only, "disposition": round.disposition,
        "stop_reason": round.stop_reason, "next_round_guidance": round.next_round_guidance,
        "negative_evidence": round.negative_evidence, "uncertainty": round.uncertainty,
    })
}

impl AdaptiveMicroscopyRound {
    pub fn validate(&self) -> Result<(), AdaptiveMicroscopyError> {
        if self.feature_id != FEATURE_ID
            || self.output_schema != OUTPUT_SCHEMA
            || self.objective.trim().is_empty()
            || self.instrument_id.trim().is_empty()
            || !canonical(&self.candidate_order)
            || !canonical(&self.negative_evidence)
            || !canonical(&self.uncertainty)
            || self.decisions.len() != self.candidate_order.len()
            || self
                .decisions
                .iter()
                .map(|decision| decision.candidate_id.clone())
                .collect::<BTreeSet<_>>()
                != self.candidate_order.iter().cloned().collect()
            || self.decisions.iter().any(|decision| {
                decision.candidate_id.trim().is_empty()
                    || decision.field_id.trim().is_empty()
                    || decision.reason.trim().is_empty()
            })
            || (self.selected_candidate_id.is_some() != self.execution.is_some())
            || (self.selected_candidate_id.is_some() != self.selected_field_id.is_some())
            || (self.selected_candidate_id.is_some() != self.selected_stratum.is_some())
            || (self.selected_candidate_id.is_none() && self.estimated_dose_milli != 0)
            || self.spent_dose_milli > self.estimated_dose_milli
            || self.remaining_dose_milli > MAX_DOSE_MILLI
            || self.next_round_guidance.trim().is_empty()
        {
            return Err(AdaptiveMicroscopyError::InvalidOutput(
                "identity, candidate partitions, dose accounting, or selected execution is inconsistent".into(),
            ));
        }
        if let Some(execution) = &self.execution {
            execution
                .validate()
                .map_err(|error| AdaptiveMicroscopyError::InvalidOutput(error.to_string()))?;
            if execution.instrument_id != self.instrument_id {
                return Err(AdaptiveMicroscopyError::InvalidOutput(
                    "instrument execution does not match the microscopy round".into(),
                ));
            }
        }
        let expected = ContentHash::of_value(&digest_input(self))
            .map_err(|error| AdaptiveMicroscopyError::Digest(error.to_string()))?;
        if expected != self.digest {
            return Err(AdaptiveMicroscopyError::InvalidOutput(
                "microscopy round digest is not content-addressed".into(),
            ));
        }
        Ok(())
    }
}

fn validate_request(request: &AdaptiveMicroscopyRequest) -> Result<(), AdaptiveMicroscopyError> {
    let calibration = &request.dose_calibration;
    if request.objective.trim().is_empty()
        || request.instrument_id.trim().is_empty()
        || request.model_system != request.material.model_system()
        || request.candidates.is_empty()
        || request.candidates.len() > MAX_CANDIDATES
        || request.stratum_targets.is_empty()
        || request.stratum_targets.len() > MAX_STRATA
        || !canonical(&request.acquired_field_ids)
        || request.acquired_field_ids.len() > MAX_FIELD_IDS
        || !canonical(
            &request
                .stratum_targets
                .iter()
                .map(|target| target.stratum_id.clone())
                .collect::<Vec<_>>(),
        )
        || request
            .stratum_targets
            .iter()
            .any(|target| target.stratum_id.trim().is_empty() || target.target_field_count == 0)
        || request.minimum_image_quality_milli > 1_000
        || request.minimum_information_gain_milli > 10_000
        || request.total_dose_budget_milli > MAX_DOSE_MILLI
        || request.dose_spent_milli > request.total_dose_budget_milli
        || calibration.calibration_id.trim().is_empty()
        || calibration.calibration_revision == 0
        || calibration.calibration_hash.as_str().len() != 64
        || calibration.instrument_id != request.instrument_id
        || calibration.intensity_parameter.trim().is_empty()
        || calibration.exposure_parameter.trim().is_empty()
        || calibration.intensity_parameter == calibration.exposure_parameter
        || calibration.minimum_intensity_permille > calibration.maximum_intensity_permille
        || calibration.maximum_intensity_permille > 1_000
        || calibration.relative_uncertainty_permille > 1_000
        || calibration.dose_milli_per_fraction_ms == 0
    {
        return Err(AdaptiveMicroscopyError::InvalidRequest(
            "objective, preclinical model, calibrated instrument, strata, bounded scores, and dose budget must be valid".into(),
        ));
    }
    let target_ids = request
        .stratum_targets
        .iter()
        .map(|target| target.stratum_id.as_str())
        .collect::<BTreeSet<_>>();
    let candidate_ids = request
        .candidates
        .iter()
        .map(|candidate| candidate.candidate_id.as_str())
        .collect::<BTreeSet<_>>();
    let field_ids = request
        .candidates
        .iter()
        .map(|candidate| candidate.field_id.as_str())
        .collect::<BTreeSet<_>>();
    if candidate_ids.len() != request.candidates.len()
        || field_ids.len() != request.candidates.len()
    {
        return Err(AdaptiveMicroscopyError::InvalidRequest(
            "candidate and field identifiers must each be unique".into(),
        ));
    }
    for candidate in &request.candidates {
        if candidate.candidate_id.trim().is_empty()
            || candidate.field_id.trim().is_empty()
            || candidate.region_id.trim().is_empty()
            || candidate.biological_stratum.trim().is_empty()
            || candidate.material != request.material
            || !target_ids.contains(candidate.biological_stratum.as_str())
            || candidate.estimator_id.trim().is_empty()
            || candidate.estimator_revision.trim().is_empty()
            || candidate.state_posterior.len() < 2
            || candidate.state_posterior.len() > MAX_STRATA
            || candidate.outcome_model.len() < 2
            || candidate.outcome_model.len() > MAX_STRATA
            || candidate.image_quality_milli > 1_000
            || candidate.spatial_novelty_milli > 1_000
            || candidate.execution.objective.trim() != request.objective.trim()
            || candidate.execution.plan.objective.trim() != request.objective.trim()
            || candidate.execution.plan.instrument_id != request.instrument_id
            || candidate.execution.plan.model_system != request.model_system
            || candidate.execution.plan.action_order.len() != 1
            || candidate.execution.actions.len() != 1
            || candidate.execution.actions[0].operation != InstrumentOperation::AcquireImage
            || candidate.execution.actions[0].instrument_id != request.instrument_id
            || candidate.execution.actions[0].model_system != request.model_system
            || candidate.execution.actions[0].action_id != candidate.execution.plan.action_order[0]
            || candidate.execution.plan.authorization_id
                != candidate.execution.authorization.authorization_id
            || candidate.execution.plan.disposition
                != super::preflight::InstrumentPreflightDisposition::Admitted
            || !candidate.execution.plan.dispatch_permitted
        {
            return Err(AdaptiveMicroscopyError::InvalidRequest(format!(
                "candidate {} must bind a unique non-human glioma field, local analysis, and one matching preflighted image action",
                candidate.candidate_id
            )));
        }
        validate_outcome_model(candidate)?;
        candidate
            .specimen_artifact
            .validate()
            .and_then(|_| candidate.analysis_artifact.validate())
            .map_err(|error| {
                AdaptiveMicroscopyError::InvalidRequest(format!(
                    "candidate {} has an invalid local-only, non-human source artifact: {error}",
                    candidate.candidate_id
                ))
            })?;
        candidate
            .execution
            .plan
            .validate()
            .map_err(|error| AdaptiveMicroscopyError::InvalidRequest(error.to_string()))?;
        for parameter in &candidate.execution.actions[0].parameters {
            if parameter
                .minimum_milli
                .zip(parameter.maximum_milli)
                .is_some_and(|(min, max)| {
                    parameter.value_milli < min || parameter.value_milli > max
                })
            {
                return Err(AdaptiveMicroscopyError::InvalidRequest(format!(
                    "candidate {} contains an out-of-range instrument parameter",
                    candidate.candidate_id
                )));
            }
        }
        let dose = estimated_dose_milli(calibration, &candidate.execution.actions[0].parameters)?;
        if dose == 0 || dose > MAX_DOSE_MILLI {
            return Err(AdaptiveMicroscopyError::InvalidRequest(format!(
                "candidate {} has an invalid calibrated illumination dose",
                candidate.candidate_id
            )));
        }
    }
    Ok(())
}

/// Construct a capture candidate only from a field whose local reference model passed its
/// independent-unit held-out gates. This is the explicit P03-analysis -> P08-execution bridge.
pub fn build_adaptive_microscopy_candidate_from_morphodynamics(
    candidate_id: &str,
    analysis: &crate::glioma::programs::p03_multimodal_ingestion_qc::microscopy_morphodynamics::MicroscopyMorphodynamicAnalysis,
    field_id: &str,
    execution: InstrumentExecutionRequest,
) -> Result<AdaptiveMicroscopyCandidate, AdaptiveMicroscopyError> {
    use crate::glioma::programs::p03_multimodal_ingestion_qc::microscopy_morphodynamics::{
        MicroscopyMorphodynamicError, MorphodynamicFieldDisposition, MorphodynamicModelDisposition,
        ESTIMATOR_ID, ESTIMATOR_REVISION,
    };
    analysis.validate().map_err(|error| match error {
        MicroscopyMorphodynamicError::InvalidOutput(message)
        | MicroscopyMorphodynamicError::Digest(message) => AdaptiveMicroscopyError::InvalidRequest(
            format!("morphodynamic analysis is invalid: {message}"),
        ),
        other => AdaptiveMicroscopyError::InvalidRequest(other.to_string()),
    })?;
    if candidate_id.trim().is_empty()
        || analysis.disposition != MorphodynamicModelDisposition::Qualified
    {
        return Err(AdaptiveMicroscopyError::InvalidRequest(
            "only a qualified independent-unit-held-out morphodynamic analysis can authorize candidate construction".into(),
        ));
    }
    let estimate = analysis
        .fields
        .iter()
        .find(|estimate| estimate.field_id == field_id)
        .ok_or_else(|| {
            AdaptiveMicroscopyError::InvalidRequest(format!(
                "field {field_id} is absent from the supplied analysis"
            ))
        })?;
    if estimate.disposition != MorphodynamicFieldDisposition::Classified
        || estimate.state_posterior.len() != analysis.state_order.len()
        || estimate
            .state_posterior
            .iter()
            .map(|value| value.state_id.clone())
            .collect::<Vec<_>>()
            != analysis.state_order
    {
        return Err(AdaptiveMicroscopyError::InvalidRequest(
            "field is not a quality-qualified, in-domain classification with a complete posterior"
                .into(),
        ));
    }
    estimate
        .source_artifact
        .validate()
        .and_then(|_| estimate.analysis_artifact.validate())
        .map_err(|error| {
            AdaptiveMicroscopyError::InvalidRequest(format!(
                "invalid local field or morphodynamic analysis artifact: {error}"
            ))
        })?;
    execution
        .plan
        .validate()
        .map_err(|error| AdaptiveMicroscopyError::InvalidRequest(error.to_string()))?;
    Ok(AdaptiveMicroscopyCandidate {
        candidate_id: candidate_id.into(),
        field_id: estimate.field_id.clone(),
        region_id: estimate.region_id.clone(),
        biological_stratum: estimate.biological_stratum.clone(),
        material: estimate.material,
        specimen_artifact: estimate.source_artifact.clone(),
        analysis_artifact: estimate.analysis_artifact.clone(),
        estimator_id: ESTIMATOR_ID.into(),
        estimator_revision: ESTIMATOR_REVISION.into(),
        state_posterior: estimate.state_posterior.clone(),
        outcome_model: analysis.outcome_model.clone(),
        image_quality_milli: estimate.image_quality_milli,
        spatial_novelty_milli: estimate.spatial_novelty_milli,
        execution,
    })
}

fn validate_research_workflow_request(
    request: &AdaptiveMicroscopyResearchWorkflowRequest,
) -> Result<(), AdaptiveMicroscopyResearchWorkflowError> {
    let calibration = &request.dose_calibration;
    let binding_fields = request
        .execution_bindings
        .iter()
        .map(|binding| binding.field_id.clone())
        .collect::<Vec<_>>();
    let binding_ids = request
        .execution_bindings
        .iter()
        .map(|binding| binding.candidate_id.clone())
        .collect::<BTreeSet<_>>();
    let target_fields = request
        .target_fields
        .iter()
        .map(|field| field.field_id.as_str())
        .collect::<BTreeSet<_>>();
    let strata = request
        .stratum_targets
        .iter()
        .map(|target| target.stratum_id.clone())
        .collect::<Vec<_>>();
    if request.objective.trim().is_empty()
        || request.instrument_id.trim().is_empty()
        || request.execution_bindings.len() > MAX_CANDIDATES
        || !canonical(&binding_fields)
        || binding_ids.len() != request.execution_bindings.len()
        || request.execution_bindings.iter().any(|binding| {
            binding.candidate_id.trim().is_empty()
                || binding.field_id.trim().is_empty()
                || !target_fields.contains(binding.field_id.as_str())
        })
        || strata.is_empty()
        || strata.len() > MAX_STRATA
        || !canonical(&strata)
        || request
            .stratum_targets
            .iter()
            .any(|target| target.stratum_id.trim().is_empty() || target.target_field_count == 0)
        || !canonical(&request.acquired_field_ids)
        || request.minimum_image_quality_milli > 1_000
        || request.minimum_information_gain_milli > 10_000
        || request.total_dose_budget_milli > MAX_DOSE_MILLI
        || request.dose_spent_milli > request.total_dose_budget_milli
        || calibration.calibration_id.trim().is_empty()
        || calibration.calibration_revision == 0
        || calibration.calibration_hash.as_str().len() != 64
        || calibration.instrument_id != request.instrument_id
        || calibration.intensity_parameter.trim().is_empty()
        || calibration.exposure_parameter.trim().is_empty()
        || calibration.intensity_parameter == calibration.exposure_parameter
        || calibration.minimum_intensity_permille > calibration.maximum_intensity_permille
        || calibration.maximum_intensity_permille > 1_000
        || calibration.relative_uncertainty_permille > 1_000
        || calibration.dose_milli_per_fraction_ms == 0
    {
        return Err(AdaptiveMicroscopyResearchWorkflowError::InvalidRequest(
            "research objective, unique target-to-preflight bindings, strata, instrument calibration, and budgets must be valid".into(),
        ));
    }
    Ok(())
}

/// Run the local morphology analysis and, only if its independent-unit validation passes,
/// prepare and execute one dose-budgeted P08 image capture using caller-owned preflight grants.
pub fn execute_glioma_adaptive_microscopy_research_workflow<E: InstrumentExecutor>(
    request: &AdaptiveMicroscopyResearchWorkflowRequest,
    executor: &mut E,
) -> Result<AdaptiveMicroscopyResearchWorkflowRun, AdaptiveMicroscopyResearchWorkflowError> {
    use crate::glioma::programs::p03_multimodal_ingestion_qc::microscopy_morphodynamics::{
        analyze_glioma_microscopy_morphodynamics, MorphodynamicFieldDisposition,
        MorphodynamicModelDisposition,
    };
    validate_research_workflow_request(request)?;
    let analysis = analyze_glioma_microscopy_morphodynamics(
        &request.analysis_request,
        &request.reference_fields,
        &request.target_fields,
    )?;
    let all_target_ids = request
        .target_fields
        .iter()
        .map(|field| field.field_id.clone())
        .collect::<Vec<_>>();
    if analysis.disposition != MorphodynamicModelDisposition::Qualified {
        return Ok(AdaptiveMicroscopyResearchWorkflowRun {
            analysis,
            adaptive_round: None,
            omitted_field_ids: all_target_ids,
            stop_reason: AdaptiveMicroscopyResearchStopReason::ReferenceModelNotQualified,
        });
    }
    let mut candidates = Vec::new();
    let mut omitted = BTreeSet::new();
    let mut classified_count = 0usize;
    for estimate in &analysis.fields {
        if estimate.disposition != MorphodynamicFieldDisposition::Classified {
            omitted.insert(estimate.field_id.clone());
            continue;
        }
        classified_count += 1;
        let Some(binding) = request
            .execution_bindings
            .iter()
            .find(|binding| binding.field_id == estimate.field_id)
        else {
            omitted.insert(estimate.field_id.clone());
            continue;
        };
        candidates.push(
            build_adaptive_microscopy_candidate_from_morphodynamics(
                &binding.candidate_id,
                &analysis,
                &estimate.field_id,
                binding.execution.clone(),
            )
            .map_err(|source| {
                AdaptiveMicroscopyResearchWorkflowError::AcquisitionPreparation {
                    analysis: Box::new(analysis.clone()),
                    source,
                }
            })?,
        );
    }
    if candidates.is_empty() {
        let stop_reason = if classified_count == 0 {
            AdaptiveMicroscopyResearchStopReason::NoClassifiedTargetField
        } else {
            AdaptiveMicroscopyResearchStopReason::NoPreflightedBindingForClassifiedField
        };
        return Ok(AdaptiveMicroscopyResearchWorkflowRun {
            analysis,
            adaptive_round: None,
            omitted_field_ids: omitted.into_iter().collect(),
            stop_reason,
        });
    }
    let adaptive_request = AdaptiveMicroscopyRequest {
        objective: request.objective.clone(),
        material: analysis.material,
        model_system: analysis.model_system,
        instrument_id: request.instrument_id.clone(),
        dose_calibration: request.dose_calibration.clone(),
        candidates,
        stratum_targets: request.stratum_targets.clone(),
        acquired_field_ids: request.acquired_field_ids.clone(),
        minimum_image_quality_milli: request.minimum_image_quality_milli,
        minimum_information_gain_milli: request.minimum_information_gain_milli,
        total_dose_budget_milli: request.total_dose_budget_milli,
        dose_spent_milli: request.dose_spent_milli,
    };
    let adaptive_round = execute_glioma_adaptive_microscopy_round(&adaptive_request, executor)
        .map_err(
            |source| AdaptiveMicroscopyResearchWorkflowError::Acquisition {
                analysis: Box::new(analysis.clone()),
                source,
            },
        )?;
    Ok(AdaptiveMicroscopyResearchWorkflowRun {
        analysis,
        adaptive_round: Some(adaptive_round),
        omitted_field_ids: omitted.into_iter().collect(),
        stop_reason: AdaptiveMicroscopyResearchStopReason::AcquisitionRoundAttempted,
    })
}

fn estimated_dose_milli(
    calibration: &MicroscopyDoseCalibration,
    parameters: &[InstrumentParameter],
) -> Result<u64, AdaptiveMicroscopyError> {
    let intensity = parameters
        .iter()
        .find(|parameter| parameter.name == calibration.intensity_parameter)
        .ok_or_else(|| {
            AdaptiveMicroscopyError::InvalidRequest(
                "image action is missing the calibrated illumination-intensity parameter".into(),
            )
        })?;
    let exposure = parameters
        .iter()
        .find(|parameter| parameter.name == calibration.exposure_parameter)
        .ok_or_else(|| {
            AdaptiveMicroscopyError::InvalidRequest(
                "image action is missing the calibrated exposure parameter".into(),
            )
        })?;
    if intensity.unit != INTENSITY_UNIT
        || exposure.unit != EXPOSURE_UNIT
        || intensity.value_milli < i64::from(calibration.minimum_intensity_permille)
        || intensity.value_milli > i64::from(calibration.maximum_intensity_permille)
        || exposure.value_milli <= 0
    {
        return Err(AdaptiveMicroscopyError::InvalidRequest(
            "illumination settings must use calibrated units and remain inside the qualified instrument range".into(),
        ));
    }
    let numerator = (intensity.value_milli as u128)
        .saturating_mul(exposure.value_milli as u128)
        .saturating_mul(calibration.dose_milli_per_fraction_ms as u128);
    let nominal = numerator.saturating_add(DOSE_SCALE - 1) / DOSE_SCALE;
    let conservative = nominal
        .saturating_mul(1_000 + u128::from(calibration.relative_uncertainty_permille))
        .saturating_add(999)
        / 1_000;
    u64::try_from(conservative).map_err(|_| {
        AdaptiveMicroscopyError::InvalidRequest("calibrated image dose overflows".into())
    })
}

fn validate_outcome_model(
    candidate: &AdaptiveMicroscopyCandidate,
) -> Result<(), AdaptiveMicroscopyError> {
    let state_ids = candidate
        .state_posterior
        .iter()
        .map(|state| state.state_id.clone())
        .collect::<Vec<_>>();
    let outcome_ids = candidate
        .outcome_model
        .iter()
        .map(|outcome| outcome.outcome_id.clone())
        .collect::<Vec<_>>();
    if !canonical(&state_ids)
        || !canonical(&outcome_ids)
        || candidate
            .state_posterior
            .iter()
            .any(|state| state.state_id.trim().is_empty() || state.probability_milli > 1_000)
        || candidate
            .state_posterior
            .iter()
            .map(|state| u32::from(state.probability_milli))
            .sum::<u32>()
            != 1_000
        || candidate.outcome_model.iter().any(|outcome| {
            outcome.outcome_id.trim().is_empty()
                || outcome.likelihood_by_state_milli.len() != candidate.state_posterior.len()
                || outcome
                    .likelihood_by_state_milli
                    .iter()
                    .any(|value| *value > 1_000)
        })
    {
        return Err(AdaptiveMicroscopyError::InvalidRequest(format!(
            "candidate {} has an invalid or non-canonical categorical state/outcome model",
            candidate.candidate_id
        )));
    }
    for (state_index, state_id) in state_ids.iter().enumerate() {
        let likelihood_sum = candidate
            .outcome_model
            .iter()
            .map(|outcome| u32::from(outcome.likelihood_by_state_milli[state_index]))
            .sum::<u32>();
        if likelihood_sum != 1_000 {
            return Err(AdaptiveMicroscopyError::InvalidRequest(format!(
                "candidate {} outcome likelihoods for state {} sum to {likelihood_sum}, not 1000",
                candidate.candidate_id, state_id
            )));
        }
    }
    Ok(())
}

fn log2_ratio_q16(numerator: u128, denominator: u128) -> u32 {
    if numerator <= denominator {
        return 0;
    }
    let mut value = (numerator << 63) / denominator;
    let mut exponent = 0_u32;
    while value >= (2_u128 << 63) {
        value >>= 1;
        exponent += 1;
    }
    let mut fraction = 0_u32;
    for bit in 0..16 {
        value = value.saturating_mul(value) >> 63;
        if value >= (2_u128 << 63) {
            value >>= 1;
            fraction |= 1 << (15 - bit);
        }
    }
    exponent.saturating_mul(65_536).saturating_add(fraction)
}

/// Fixed-point expected Shannon information gain, in milli-bits, and normalized posterior
/// entropy. Integer log2 avoids platform-dependent floating-point acquisition order.
fn scientific_estimate(candidate: &AdaptiveMicroscopyCandidate) -> (u16, u16) {
    let prior_entropy_q16 = candidate.state_posterior.iter().fold(0_u128, |sum, state| {
        let probability = u128::from(state.probability_milli);
        if probability == 0 {
            sum
        } else {
            sum.saturating_add(probability * u128::from(log2_ratio_q16(1_000, probability)))
        }
    });
    let prior_entropy_milli = ((prior_entropy_q16 + 32_768) / 65_536) as u64;
    let mut expected_posterior_q16 = 0_u128;
    for outcome in &candidate.outcome_model {
        let joint = candidate
            .state_posterior
            .iter()
            .zip(&outcome.likelihood_by_state_milli)
            .map(|(state, likelihood)| {
                u128::from(state.probability_milli) * u128::from(*likelihood)
            })
            .collect::<Vec<_>>();
        let outcome_mass = joint.iter().sum::<u128>();
        if outcome_mass == 0 {
            continue;
        }
        for mass in joint.into_iter().filter(|mass| *mass > 0) {
            expected_posterior_q16 = expected_posterior_q16.saturating_add(
                mass.saturating_mul(u128::from(log2_ratio_q16(outcome_mass, mass))),
            );
        }
    }
    let expected_posterior_milli = ((expected_posterior_q16 + 32_768_000) / 65_536_000) as u64;
    let gain = prior_entropy_milli
        .saturating_sub(expected_posterior_milli)
        .min(u64::from(u16::MAX));
    let maximum_entropy_milli =
        (u64::from(log2_ratio_q16(candidate.state_posterior.len() as u128, 1))
            .saturating_mul(1_000)
            + 32_768)
            / 65_536;
    let uncertainty = (prior_entropy_milli
        .saturating_mul(1_000)
        .checked_div(maximum_entropy_milli)
        .unwrap_or(0)
        .min(1_000)) as u16;
    (gain as u16, uncertainty)
}

fn stratum_debt(target: &MicroscopyStratumTarget) -> u16 {
    if target.acquired_field_count >= target.target_field_count {
        return 0;
    }
    let remaining = u32::from(target.target_field_count - target.acquired_field_count);
    let total = u32::from(target.target_field_count);
    (remaining * 1_000).div_ceil(total) as u16
}

fn priority(
    candidate: &AdaptiveMicroscopyCandidate,
    gain: u16,
    uncertainty: u16,
    debt: u16,
    dose: u64,
) -> u64 {
    let utility = u128::from(gain)
        .saturating_mul(1_000 + u128::from(uncertainty))
        .saturating_mul(u128::from(candidate.image_quality_milli))
        .saturating_mul(1_000 + u128::from(candidate.spatial_novelty_milli))
        .saturating_mul(1_000 + u128::from(debt));
    u64::try_from(utility / u128::from(dose.max(1))).unwrap_or(u64::MAX)
}

fn round_digest(round: &AdaptiveMicroscopyRound) -> Result<ContentHash, AdaptiveMicroscopyError> {
    ContentHash::of_value(&digest_input(round))
        .map_err(|error| AdaptiveMicroscopyError::Digest(error.to_string()))
}

fn empty_round(
    request: &AdaptiveMicroscopyRequest,
    disposition: AdaptiveMicroscopyDisposition,
    stop_reason: AdaptiveMicroscopyStopReason,
    mut decisions: Vec<MicroscopyCandidateDecision>,
    guidance: &str,
) -> Result<AdaptiveMicroscopyRound, AdaptiveMicroscopyError> {
    decisions.sort_by(|left, right| left.candidate_id.cmp(&right.candidate_id));
    let mut round = AdaptiveMicroscopyRound {
        feature_id: FEATURE_ID.into(),
        output_schema: OUTPUT_SCHEMA.into(),
        objective: request.objective.clone(),
        instrument_id: request.instrument_id.clone(),
        candidate_order: decisions
            .iter()
            .map(|decision| decision.candidate_id.clone())
            .collect(),
        decisions,
        selected_candidate_id: None,
        selected_field_id: None,
        selected_stratum: None,
        estimated_dose_milli: 0,
        spent_dose_milli: 0,
        remaining_dose_milli: request
            .total_dose_budget_milli
            .saturating_sub(request.dose_spent_milli),
        execution: None,
        simulation_only: false,
        disposition,
        stop_reason,
        next_round_guidance: guidance.into(),
        negative_evidence: Vec::new(),
        uncertainty: Vec::new(),
        digest: ContentHash::of_bytes(b"pending"),
    };
    round.digest = round_digest(&round)?;
    round.validate()?;
    Ok(round)
}

/// Execute one adaptive microscopy round for local, non-human preclinical glioma material.
///
/// Required spatial/state strata are filled first. On that coverage frontier, the fixed-point
/// policy favors information-rich, uncertain, novel, good-quality fields per conservative dose.
/// A caller analyzes the returned local artifact, updates estimates, and calls again for the next
/// round; no image is fabricated or interpreted by this acquisition controller.
pub fn execute_glioma_adaptive_microscopy_round<E: InstrumentExecutor>(
    request: &AdaptiveMicroscopyRequest,
    executor: &mut E,
) -> Result<AdaptiveMicroscopyRound, AdaptiveMicroscopyError> {
    validate_request(request)?;
    let remaining_budget = request
        .total_dose_budget_milli
        .saturating_sub(request.dose_spent_milli);
    if remaining_budget == 0 {
        let decisions = request
            .candidates
            .iter()
            .map(|candidate| MicroscopyCandidateDecision {
                candidate_id: candidate.candidate_id.clone(),
                field_id: candidate.field_id.clone(),
                disposition: MicroscopyCandidateDisposition::DoseBudgetBlocked,
                estimated_dose_milli: estimated_dose_milli(
                    &request.dose_calibration,
                    &candidate.execution.actions[0].parameters,
                )
                .unwrap_or(0),
                expected_information_gain_milli: scientific_estimate(candidate).0,
                posterior_uncertainty_milli: scientific_estimate(candidate).1,
                priority_score: 0,
                reason: "the specimen's calibrated imaging-dose budget is exhausted".into(),
            })
            .collect();
        return empty_round(request, AdaptiveMicroscopyDisposition::DoseBudgetExhausted,
            AdaptiveMicroscopyStopReason::DoseBudgetExhausted, decisions,
            "Stop imaging; preserve the dose-limited dataset and route existing frames to local analysis.");
    }

    let targets = request
        .stratum_targets
        .iter()
        .map(|target| (target.stratum_id.as_str(), target))
        .collect::<BTreeMap<_, _>>();
    let maximum_debt = request
        .stratum_targets
        .iter()
        .map(stratum_debt)
        .max()
        .unwrap_or(0);
    let frontier_strata = request
        .stratum_targets
        .iter()
        .filter(|target| stratum_debt(target) == maximum_debt && maximum_debt > 0)
        .map(|target| target.stratum_id.as_str())
        .collect::<BTreeSet<_>>();
    let acquired = request
        .acquired_field_ids
        .iter()
        .map(String::as_str)
        .collect::<BTreeSet<_>>();
    let mut decisions = Vec::with_capacity(request.candidates.len());
    let mut eligible = Vec::new();
    let mut any_frontier_candidate = frontier_strata.is_empty();
    let mut any_frontier_quality_information_candidate = false;
    let mut any_frontier_candidate_fits_budget = false;
    let mut any_quality_information_candidate = false;
    let mut any_candidate_fits_budget = false;

    for candidate in &request.candidates {
        let dose = estimated_dose_milli(
            &request.dose_calibration,
            &candidate.execution.actions[0].parameters,
        )?;
        let (gain, uncertainty) = scientific_estimate(candidate);
        let debt = stratum_debt(targets[candidate.biological_stratum.as_str()]);
        let (disposition, reason) = if acquired.contains(candidate.field_id.as_str()) {
            (
                MicroscopyCandidateDisposition::AlreadyAcquired,
                "field was already acquired in this imaging run".to_string(),
            )
        } else if candidate.image_quality_milli < request.minimum_image_quality_milli {
            (
                MicroscopyCandidateDisposition::QualityBlocked,
                "local analysis predicts image quality below the acquisition floor".into(),
            )
        } else if gain < request.minimum_information_gain_milli {
            (
                MicroscopyCandidateDisposition::InformationBlocked,
                "predicted information gain is below the configured threshold".into(),
            )
        } else {
            any_quality_information_candidate = true;
            let on_coverage_frontier = frontier_strata.is_empty()
                || frontier_strata.contains(candidate.biological_stratum.as_str());
            if on_coverage_frontier {
                any_frontier_quality_information_candidate = true;
            }
            if dose > remaining_budget {
                (
                    MicroscopyCandidateDisposition::DoseBudgetBlocked,
                    "conservative calibrated light dose exceeds the remaining specimen budget"
                        .into(),
                )
            } else {
                any_candidate_fits_budget = true;
                if !frontier_strata.is_empty()
                    && !frontier_strata.contains(candidate.biological_stratum.as_str())
                {
                    (
                        MicroscopyCandidateDisposition::CoverageFrontierBlocked,
                        "a most-undercovered required glioma stratum must be sampled first".into(),
                    )
                } else {
                    any_frontier_candidate = true;
                    any_frontier_candidate_fits_budget = true;
                    eligible.push((
                        priority(candidate, gain, uncertainty, debt, dose),
                        candidate.candidate_id.as_str(),
                        candidate,
                    ));
                    (
                        MicroscopyCandidateDisposition::EligibleNotSelected,
                        "eligible for this round's coverage frontier".into(),
                    )
                }
            }
        };
        let score = if disposition == MicroscopyCandidateDisposition::EligibleNotSelected {
            priority(candidate, gain, uncertainty, debt, dose)
        } else {
            0
        };
        decisions.push(MicroscopyCandidateDecision {
            candidate_id: candidate.candidate_id.clone(),
            field_id: candidate.field_id.clone(),
            disposition,
            estimated_dose_milli: dose,
            expected_information_gain_milli: gain,
            posterior_uncertainty_milli: uncertainty,
            priority_score: score,
            reason,
        });
    }

    if eligible.is_empty() {
        let (disposition, stop_reason, guidance) = if (any_frontier_quality_information_candidate
            && !any_frontier_candidate_fits_budget)
            || (any_quality_information_candidate && !any_candidate_fits_budget)
        {
            (AdaptiveMicroscopyDisposition::DoseBudgetExhausted, AdaptiveMicroscopyStopReason::DoseBudgetExhausted,
                "No quality- and information-qualified field fits the remaining dose budget; analyze existing frames or request a separately reviewed budget change.")
        } else if !any_frontier_candidate {
            (AdaptiveMicroscopyDisposition::CoverageFrontierUnresolved, AdaptiveMicroscopyStopReason::RequiredStratumHasNoUsableField,
                "A most-undercovered required glioma stratum has no eligible field; refresh local analysis or revise the sampling target before imaging elsewhere.")
        } else {
            (AdaptiveMicroscopyDisposition::NoEligibleField, AdaptiveMicroscopyStopReason::NoEligibleCandidate,
                "No field passed quality, information, duplicate, coverage, and dose gates; leave this round unresolved rather than inventing a measurement.")
        };
        return empty_round(request, disposition, stop_reason, decisions, guidance);
    }

    eligible.sort_by(|left, right| right.0.cmp(&left.0).then_with(|| left.1.cmp(right.1)));
    let selected = eligible[0].2;
    for decision in &mut decisions {
        if decision.candidate_id == selected.candidate_id {
            decision.disposition = MicroscopyCandidateDisposition::Selected;
            decision.reason = "highest information-per-dose candidate among the most-undercovered required strata".into();
        }
    }
    decisions.sort_by(|left, right| left.candidate_id.cmp(&right.candidate_id));

    // This seam rechecks live authorization and interlocks; the planner cannot dispatch directly.
    let simulation_only = executor.simulation_only();
    let execution = execute_glioma_instrument_plan(&selected.execution, executor)?;
    let dispatched = execution
        .results
        .iter()
        .any(|result| result.started_tick.is_some());
    let estimated_dose = estimated_dose_milli(
        &request.dose_calibration,
        &selected.execution.actions[0].parameters,
    )?;
    let spent_dose = if dispatched { estimated_dose } else { 0 };
    let spent_dose = if simulation_only { 0 } else { spent_dose };
    let remaining_dose = remaining_budget.saturating_sub(spent_dose);
    let (disposition, stop_reason, guidance) = match execution.disposition {
        InstrumentExecutionDisposition::Completed if simulation_only =>
            (AdaptiveMicroscopyDisposition::Simulated, AdaptiveMicroscopyStopReason::CaptureExecuted,
                "Synthetic dry run only: no image or biological observation was made. Use a qualified local microscope gateway before scientific analysis.".to_string()),
        InstrumentExecutionDisposition::Completed =>
            (AdaptiveMicroscopyDisposition::Executed, AdaptiveMicroscopyStopReason::CaptureExecuted,
                "Analyze the new local field, refresh state uncertainty and stratum coverage, then submit a new candidate set before capturing again.".to_string()),
        InstrumentExecutionDisposition::Negative =>
            (AdaptiveMicroscopyDisposition::Negative, AdaptiveMicroscopyStopReason::NegativeCapture,
                "Preserve the negative/null capture; update local evidence before considering another field.".to_string()),
        InstrumentExecutionDisposition::Partial | InstrumentExecutionDisposition::Unresolved =>
            (AdaptiveMicroscopyDisposition::Partial, AdaptiveMicroscopyStopReason::PartialCapture,
                "Reconcile the partial or unresolved capture locally; do not retry or infer a complete image until the gateway is reconciled.".to_string()),
        InstrumentExecutionDisposition::Blocked | InstrumentExecutionDisposition::Failed =>
            (AdaptiveMicroscopyDisposition::Blocked, AdaptiveMicroscopyStopReason::InstrumentPreflightOrAuthorizationBlocked,
                "Inspect the instrument run and interlocks; refresh preflight and authorization before another physical capture.".to_string()),
    };
    let mut negative_evidence = execution
        .negative_evidence
        .iter()
        .cloned()
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect::<Vec<_>>();
    let mut uncertainty = execution
        .uncertainty
        .iter()
        .cloned()
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect::<Vec<_>>();
    if simulation_only {
        negative_evidence
            .push("simulation-only-instrument-operation-is-not-biological-evidence".into());
        negative_evidence.sort();
        negative_evidence.dedup();
        uncertainty.push("simulation-only-execution".into());
        uncertainty.sort();
        uncertainty.dedup();
    }
    let mut round = AdaptiveMicroscopyRound {
        feature_id: FEATURE_ID.into(),
        output_schema: OUTPUT_SCHEMA.into(),
        objective: request.objective.clone(),
        instrument_id: request.instrument_id.clone(),
        candidate_order: decisions
            .iter()
            .map(|decision| decision.candidate_id.clone())
            .collect(),
        decisions,
        selected_candidate_id: Some(selected.candidate_id.clone()),
        selected_field_id: Some(selected.field_id.clone()),
        selected_stratum: Some(selected.biological_stratum.clone()),
        estimated_dose_milli: estimated_dose,
        spent_dose_milli: spent_dose,
        remaining_dose_milli: remaining_dose,
        execution: Some(execution),
        simulation_only,
        disposition,
        stop_reason,
        next_round_guidance: guidance,
        negative_evidence,
        uncertainty,
        digest: ContentHash::of_bytes(b"pending"),
    };
    round.digest = round_digest(&round)?;
    round.validate()?;
    Ok(round)
}

